        });
    }

    fn emitListResource(self: *FunctionEmitter, value: Ir.Instruction.ListResource, comptime operation: []const u8) Error!void {
        const type_value = try self.valueType(value.operand);
        const collection = try self.collectionInfo(type_value);
        if (collection.view or collection.length != null)
            return error.UnsupportedInstruction;
        _ = try llvmType(self.allocator, self.program, collection.element);
        const serial = self.nextTemporary();
        try self.write("  %t{d}.owned = extractvalue {s} %v{d}, 0\n", .{ serial, try llvmType(self.allocator, self.program, type_value), value.operand });
        try self.write("  call fastcc void @{s}(ptr %t{d}.owned, i64 {d})\n", .{
            operation,
            serial,
            if (value.ownership == .root) @as(i8, -24) else -16,
        });
    }

    fn emitBoundsFailure(self: *FunctionEmitter, block_id: usize, serial: usize, index: Ir.ValueId, position: @TypeOf(@as(Ir.Instruction.CollectionLoad, undefined).position)) Error!void {
        if (position.file >= self.program.files.len) return error.InvalidProgram;
        try self.write("  br i1 %t{d}.index.invalid, label %b{d}.fail{d}, label %b{d}.cont{d}\n", .{ serial, block_id, serial, block_id, serial });
        try self.write("b{d}.fail{d}:\n", .{ block_id, serial });
        try self.write("  call fastcc void @sx_bounds(ptr @sx.file.{d}, i64 {d}, i64 {d}, i64 %v{d}, i64 %t{d}.count)\n", .{ position.file, position.line, position.column, index, serial });
        try self.write("  unreachable\nb{d}.cont{d}:\n", .{ block_id, serial });
    }

    fn emitConversionFailure(self: *FunctionEmitter, block_id: usize, serial: usize, value: Ir.Instruction.Convert, exact: bool) Error!void {
        if (value.position.file >= self.program.files.len) return error.InvalidProgram;
        if (exact) {
            try self.write("  br i1 %t{d}.exact, label %b{d}.cont{d}, label %b{d}.fail{d}\n", .{ serial, block_id, serial, block_id, serial });
        } else {
            try self.write("  br i1 %t{d}.invalid, label %b{d}.fail{d}, label %b{d}.cont{d}\n", .{ serial, block_id, serial, block_id, serial });
        }
        try self.write("b{d}.fail{d}:\n", .{ block_id, serial });
        try self.write("  call fastcc void @sx_conversion(ptr @sx.file.{d}, i64 {d}, i64 {d})\n", .{ value.position.file, value.position.line, value.position.column });
        try self.write("  unreachable\nb{d}.cont{d}:\n", .{ block_id, serial });
    }

    fn emitAssert(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Assert) Error!void {
        if (try self.valueType(value.condition) != .bool or
            try self.valueType(value.message) != .str or
            value.position.file >= self.program.files.len)
        {
            return error.InvalidProgram;
        }
        const serial = self.nextTemporary();
        try self.write("  br i1 %v{d}, label %b{d}.assert.cont{d}, label %b{d}.assert.fail{d}\n", .{
            value.condition, block_id, serial, block_id, serial,
        });
        try self.write("b{d}.assert.fail{d}:\n", .{ block_id, serial });
        try self.write("  call fastcc void @sx_assert(ptr @sx.file.{d}, i64 {d}, i64 {d}, ptr %v{d})\n", .{
            value.position.file, value.position.line, value.position.column, value.message,
        });
        try self.write("  unreachable\nb{d}.assert.cont{d}:\n", .{ block_id, serial });
    }

    fn copyValue(self: *FunctionEmitter, result: Ir.ValueId, operand: Ir.ValueId) Error!void {
        const result_type = try self.valueType(result);
        const operand_type = try self.valueType(operand);
        if (result_type == .uint and operand_type.functionIndex() != null) {
            const target = directFunctionReference(self.function, operand) orelse
                return error.UnsupportedInstruction;
            if (target >= self.program.functions.len or self.program.functions[target].capture_types.len != 0)
                return error.UnsupportedInstruction;
            return self.write("  %v{d} = ptrtoint ptr @sx.c.callback.{d} to i64\n", .{ result, target });
        }
        if (operand_type == .uint and result_type.functionIndex() != null) {
            const serial = self.nextTemporary();
            try self.write("  %t{d}.function.pointer = inttoptr i64 %v{d} to ptr\n", .{ serial, operand });
            try self.write("  %t{d}.function.code = insertvalue {{ ptr, ptr, ptr }} zeroinitializer, ptr %t{d}.function.pointer, 0\n", .{ serial, serial });
            try self.write("  %v{d} = insertvalue {{ ptr, ptr, ptr }} %t{d}.function.code, ptr null, 1\n", .{ result, serial });
            return;
        }
        if (result_type == .uint and pointerRepresentation(self.program, operand_type))
            return self.write("  %v{d} = ptrtoint ptr %v{d} to i64\n", .{ result, operand });
        if (operand_type == .uint and pointerRepresentation(self.program, result_type))
            return self.write("  %v{d} = inttoptr i64 %v{d} to ptr\n", .{ result, operand });
        if (result_type != operand_type) return error.UnsupportedInstruction;
        const type_name = try llvmType(self.allocator, self.program, result_type);
        try self.write("  %v{d} = select i1 true, {s} %v{d}, {s} %v{d}\n", .{
            result,
            type_name,
            operand,
            type_name,
            operand,
        });
    }

    fn emitFunctionReference(self: *FunctionEmitter, value: Ir.Instruction.FunctionReference) Error!void {
        if (value.function >= self.program.functions.len) return error.InvalidProgram;
        const result_type = try self.valueType(value.result);
        const function_type_index = result_type.functionIndex() orelse return error.InvalidProgram;
        if (function_type_index >= self.program.function_types.len) return error.InvalidProgram;
        const function_type = self.program.function_types[function_type_index];
        const target = self.program.functions[value.function];
        if (value.captures.len != target.capture_types.len or
            !std.mem.eql(Ir.Type, function_type.parameter_types, target.parameter_types) or
            function_type.return_type != target.return_type)
        {
            return error.InvalidProgram;
        }
        for (value.captures, target.capture_types) |capture, capture_type| {
            if (capture_type != .address or try self.valueType(capture) != capture_type)
                return error.UnsupportedInstruction;
        }
        const serial = self.nextTemporary();
        const environment = if (value.captures.len == 0)
            "null"
        else environment: {
            const environment_type = try closureEnvironmentType(self.allocator, self.program, target.capture_types);
            try self.write("  %t{d}.closure.environment = alloca {s}\n", .{ serial, environment_type });
            for (value.captures, target.capture_types, 0..) |capture, capture_type, capture_index| {
                try self.write("  %t{d}.closure.capture.{d} = getelementptr {s}, ptr %t{d}.closure.environment, i32 0, i32 {d}\n", .{
                    serial,
                    capture_index,
                    environment_type,
                    serial,
                    capture_index,
                });
                try self.write("  store {s} %v{d}, ptr %t{d}.closure.capture.{d}\n", .{
                    try llvmType(self.allocator, self.program, capture_type),
                    capture,
                    serial,
                    capture_index,
                });
            }
            break :environment try std.fmt.allocPrint(self.allocator, "%t{d}.closure.environment", .{serial});
        };
        try self.write("  %t{d}.closure.code = insertvalue {{ ptr, ptr, ptr }} zeroinitializer, ptr @sx_{d}, 0\n", .{
            serial,
            value.function,
        });
        try self.write("  %v{d} = insertvalue {{ ptr, ptr, ptr }} %t{d}.closure.code, ptr {s}, 1\n", .{
            value.result,
            serial,
            environment,
        });
    }

    fn emitEnumInit(self: *FunctionEmitter, value: Ir.Instruction.EnumInit) Error!void {
        if (value.enumeration >= self.program.enums.len) return error.InvalidProgram;
        const enumeration = self.program.enums[value.enumeration];
        if (value.variant >= enumeration.variants.len or
            try self.valueType(value.result) != Ir.Type.structure(enumeration.type_index))
            return error.InvalidProgram;
        const variant = enumeration.variants[value.variant];
        if (value.values.len != variant.associated_types.len) return error.InvalidProgram;
        for (value.values, variant.associated_types) |operand, associated_type| {
            if (try self.valueType(operand) != associated_type) return error.InvalidProgram;
        }
        if (plainTagEnum(self.program, value.enumeration)) {
            if (value.values.len != 0) return error.InvalidProgram;
            return self.write("  %v{d} = add i64 0, {d}\n", .{ value.result, value.variant });
        }
        if (try rawEnumType(self.program, value.enumeration)) |raw_type| {
            if (value.values.len != 0) return error.InvalidProgram;
            const raw_value = variant.raw_value orelse return error.InvalidProgram;
            const serial = self.nextTemporary();
            const type_name = try llvmType(self.allocator, self.program, try self.valueType(value.result));
            try self.write("  %t{d}.enum.tagged = insertvalue {s} poison, i64 {d}, 0\n", .{ serial, type_name, value.variant });
            switch (raw_value) {
                .integer => |integer| {
                    if (raw_type != .int) return error.InvalidProgram;
                    return self.write("  %v{d} = insertvalue {s} %t{d}.enum.tagged, i64 {d}, 1\n", .{ value.result, type_name, serial, integer });
                },
                .string => |string| {
                    if (raw_type != .str) return error.InvalidProgram;
                    try self.write(
                        "  %t{d}.enum.raw = getelementptr {{ i64, [{d} x i8] }}, ptr @sx.enum.raw.{d}.{d}, i32 0, i32 0\n",
                        .{ serial, string.len, value.enumeration, value.variant },
                    );
                    return self.write("  %v{d} = insertvalue {s} %t{d}.enum.tagged, ptr %t{d}.enum.raw, 1\n", .{ value.result, type_name, serial, serial });
                },
            }
        }
        _ = try enumPayloadStorageSlots(self.program, value.enumeration, 0);
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, try self.valueType(value.result));
        try self.write("  %t{d}.enum = alloca {s}\n", .{ serial, type_name });
        try self.write("  store {s} zeroinitializer, ptr %t{d}.enum\n", .{ type_name, serial });
        try self.write("  store i64 {d}, ptr %t{d}.enum\n", .{ value.variant, serial });
        var offset: usize = 8;
        for (value.values, variant.associated_types, 0..) |operand, associated_type, index| {
            try self.write("  %t{d}.enum.payload.{d} = getelementptr i8, ptr %t{d}.enum, i64 {d}\n", .{
                serial,
                index,
                serial,
                offset,
            });
            try self.write("  store {s} %v{d}, ptr %t{d}.enum.payload.{d}\n", .{
                try llvmType(self.allocator, self.program, associated_type),
                operand,
                serial,
                index,
            });
            offset += 8 * try llvmStorageSlots(self.program, associated_type, 0);
        }
        try self.write("  %v{d} = load {s}, ptr %t{d}.enum\n", .{ value.result, type_name, serial });
    }

    fn emitEnumTest(self: *FunctionEmitter, value: Ir.Instruction.EnumTest) Error!void {
        if (value.enumeration >= self.program.enums.len) return error.InvalidProgram;
        const enumeration = self.program.enums[value.enumeration];
        if (value.variant >= enumeration.variants.len or
            try self.valueType(value.operand) != Ir.Type.structure(self.program.enums[value.enumeration].type_index) or
            try self.valueType(value.result) != .bool)
        {
            return error.InvalidProgram;
        }
        if (plainTagEnum(self.program, value.enumeration))
            return self.write("  %v{d} = icmp eq i64 %v{d}, {d}\n", .{ value.result, value.operand, value.variant });
        if ((try rawEnumType(self.program, value.enumeration)) == null)
            _ = try enumPayloadStorageSlots(self.program, value.enumeration, 0);
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, try self.valueType(value.operand));
        try self.write("  %t{d}.enum.tag = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.operand });
        try self.write("  %v{d} = icmp eq i64 %t{d}.enum.tag, {d}\n", .{ value.result, serial, value.variant });
    }

    fn emitEnumPayload(self: *FunctionEmitter, value: Ir.Instruction.EnumPayload) Error!void {
        if (value.enumeration >= self.program.enums.len) return error.InvalidProgram;
        const enumeration = self.program.enums[value.enumeration];
        if (value.variant >= enumeration.variants.len or
            try self.valueType(value.operand) != Ir.Type.structure(enumeration.type_index))
            return error.InvalidProgram;
        const variant = enumeration.variants[value.variant];
        if (value.index >= variant.associated_types.len or
            try self.valueType(value.result) != variant.associated_types[value.index])
            return error.InvalidProgram;
        _ = try enumPayloadStorageSlots(self.program, value.enumeration, 0);
        var offset: usize = 8;
        for (variant.associated_types[0..value.index]) |associated_type|
            offset += 8 * try llvmStorageSlots(self.program, associated_type, 0);
        const serial = self.nextTemporary();
        const enum_type = try llvmType(self.allocator, self.program, try self.valueType(value.operand));
        const payload_type = try llvmType(self.allocator, self.program, try self.valueType(value.result));
        try self.write("  %t{d}.enum = alloca {s}\n", .{ serial, enum_type });
        try self.write("  store {s} %v{d}, ptr %t{d}.enum\n", .{ enum_type, value.operand, serial });
        try self.write("  %t{d}.enum.payload = getelementptr i8, ptr %t{d}.enum, i64 {d}\n", .{ serial, serial, offset });
        try self.write("  %v{d} = load {s}, ptr %t{d}.enum.payload\n", .{ value.result, payload_type, serial });
    }

    fn emitEnumRaw(self: *FunctionEmitter, value: Ir.Instruction.EnumRaw) Error!void {
        if (value.enumeration >= self.program.enums.len) return error.InvalidProgram;
        const enumeration = self.program.enums[value.enumeration];
        const raw_type = (try rawEnumType(self.program, value.enumeration)) orelse return error.InvalidProgram;
        if (try self.valueType(value.operand) != Ir.Type.structure(enumeration.type_index) or
            try self.valueType(value.result) != raw_type)
            return error.InvalidProgram;
        const enum_type = try llvmType(self.allocator, self.program, try self.valueType(value.operand));
        try self.write("  %v{d} = extractvalue {s} %v{d}, 1\n", .{ value.result, enum_type, value.operand });
    }

    fn emitOptionalNull(self: *FunctionEmitter, value: Ir.Instruction.OptionalNull) Error!void {
