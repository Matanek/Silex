fn plainValue(program: Ir.Program, type_value: Ir.Type, depth: usize) bool {
    if (type_value.isNumeric() or type_value == .bool) return true;
    const index = type_value.structureIndex() orelse return false;
    if (index >= program.structures.len or depth >= program.structures.len) return false;
    const structure = program.structures[index];
    if (structure.is_class or structure.is_static or structure.is_protocol or structure.collection != null)
        return false;
    for (structure.fields) |field| if (!plainValue(program, field.type, depth + 1)) return false;
    return true;
}

fn classType(program: Ir.Program, type_value: Ir.Type) bool {
    const index = type_value.structureIndex() orelse return false;
    return index < program.structures.len and program.structures[index].is_class;
}

fn pointerRepresentation(program: Ir.Program, type_value: Ir.Type) bool {
    return type_value == .address or type_value == .str or
        type_value.functionIndex() != null or classType(program, type_value);
}

fn enumIndexForStructure(program: Ir.Program, structure_index: usize) ?usize {
    for (program.enums, 0..) |enumeration, index| {
        if (enumeration.type_index == structure_index) return index;
    }
    return null;
}

fn plainTagEnum(program: Ir.Program, enumeration_index: usize) bool {
    if (enumeration_index >= program.enums.len) return false;
    const enumeration = program.enums[enumeration_index];
    if (enumeration.raw_type != null) return false;
    for (enumeration.variants) |variant| {
        if (variant.associated_types.len != 0 or variant.raw_value != null) return false;
    }
    return true;
}

fn plainTagEnumType(program: Ir.Program, type_value: Ir.Type) bool {
    const structure_index = type_value.structureIndex() orelse return false;
    const enumeration_index = enumIndexForStructure(program, structure_index) orelse return false;
    return plainTagEnum(program, enumeration_index);
}

fn rawEnumType(program: Ir.Program, enumeration_index: usize) Error!?Ir.Type {
    if (enumeration_index >= program.enums.len) return error.InvalidProgram;
    const enumeration = program.enums[enumeration_index];
    const raw_type = enumeration.raw_type orelse return null;
    if (raw_type != .int and raw_type != .str) return error.InvalidProgram;
    for (enumeration.variants) |variant| {
        if (variant.associated_types.len != 0) return error.InvalidProgram;
        const raw_value = variant.raw_value orelse return error.InvalidProgram;
        switch (raw_value) {
            .integer => if (raw_type != .int) return error.InvalidProgram,
            .string => if (raw_type != .str) return error.InvalidProgram,
        }
    }
    return raw_type;
}

fn enumPayloadStorageSlots(program: Ir.Program, enumeration_index: usize, depth: usize) Error!usize {
    if (enumeration_index >= program.enums.len) return error.InvalidProgram;
    if (depth >= program.structures.len + program.enums.len + 8) return error.UnsupportedType;
    const enumeration = program.enums[enumeration_index];
    if (enumeration.raw_type != null) return error.UnsupportedType;
    var maximum: usize = 0;
    for (enumeration.variants) |variant| {
        if (variant.raw_value != null) return error.UnsupportedType;
        var width: usize = 0;
        for (variant.associated_types) |associated_type|
            width += try llvmStorageSlots(program, associated_type, depth + 1);
        maximum = @max(maximum, width);
    }
    if (maximum == 0) return error.UnsupportedType;
    return maximum;
}

fn protocolPayloadStorageSlots(program: Ir.Program, protocol_index: usize, depth: usize) Error!usize {
    if (protocol_index >= program.structures.len or !program.structures[protocol_index].is_protocol)
        return error.InvalidProgram;
    if (depth >= program.structures.len + program.enums.len + 8) return error.UnsupportedType;
    var maximum: usize = 0;
    for (program.structures, 0..) |structure, candidate| {
        if (structure.is_protocol or !irConforms(program, candidate, protocol_index)) continue;
        const slots = llvmStorageSlots(program, .structure(candidate), depth + 1) catch |err| {
            std.debug.print(
                "silex LLVM evaluation: protocol '{s}' cannot store conformer '{s}': {t}\n",
                .{ program.structures[protocol_index].name, structure.name, err },
            );
            return err;
        };
        maximum = @max(maximum, slots);
    }
    return maximum;
}

fn irConforms(program: Ir.Program, structure_index: usize, protocol_index: usize) bool {
    if (structure_index >= program.structures.len or protocol_index >= program.structures.len)
        return false;
    var current: ?usize = structure_index;
    var depth: usize = 0;
    while (current) |candidate| : (depth += 1) {
        if (candidate >= program.structures.len or depth >= program.structures.len) return false;
        for (program.structures[candidate].conformances) |conformance|
            if (conformance == protocol_index) return true;
        current = program.structures[candidate].base;
    }
    return false;
}

fn llvmStorageSlots(program: Ir.Program, type_value: Ir.Type, depth: usize) Error!usize {
    if (depth >= program.structures.len + program.enums.len + 8) return error.UnsupportedType;
    if (type_value.optionalChild()) |child|
        return 1 + try llvmStorageSlots(program, child, depth + 1);
    if (type_value.functionIndex()) |function_type| {
        if (function_type >= program.function_types.len) return error.InvalidProgram;
        return 3;
    }
    if (type_value.structureIndex()) |structure_index| {
        if (structure_index >= program.structures.len) return error.InvalidProgram;
        if (enumIndexForStructure(program, structure_index)) |enumeration_index| {
            if (plainTagEnum(program, enumeration_index)) return 1;
            if ((try rawEnumType(program, enumeration_index)) != null) return 2;
            return 1 + try enumPayloadStorageSlots(program, enumeration_index, depth + 1);
        }
        const structure = program.structures[structure_index];
        if (structure.is_class) return 1;
        if (structure.is_protocol)
            return 1 + try protocolPayloadStorageSlots(program, structure_index, depth + 1);
        if (structure.is_static) return error.UnsupportedType;
        if (structure.collection != null) return 2;
        var result: usize = 0;
        for (structure.fields) |field| {
            result += llvmStorageSlots(program, field.type, depth + 1) catch |err| {
                std.debug.print(
                    "silex LLVM evaluation: cannot size structure '{s}' field '{s}': {t}\n",
                    .{ structure.name, field.name, err },
                );
                return err;
            };
        }
        return result;
    }
    return switch (type_value) {
        .void => 0,
        .bool,
        .int8,
        .uint8,
        .int16,
        .uint16,
        .int32,
        .uint32,
        .int,
        .uint,
        .float32,
        .float64,
        .str,
        .address,
        => 1,
        else => error.UnsupportedType,
    };
}

fn materialClassStorage(program: Ir.Program, structure_index: usize) bool {
    if (structure_index >= program.structures.len) return false;
    const structure = program.structures[structure_index];
    if (!structure.is_class or structure.base != null) return false;
    for (structure.fields) |field| {
        _ = llvmStorageSlots(program, field.type, 0) catch return false;
    }
    return true;
}

fn classStorageSlots(program: Ir.Program, structure_index: usize) Error!usize {
    if (structure_index >= program.structures.len) return error.InvalidProgram;
    const structure = program.structures[structure_index];
    if (!structure.is_class or structure.base != null) return error.UnsupportedType;
    var slots: usize = 0;
    for (structure.fields) |field|
        slots = std.math.add(usize, slots, try llvmStorageSlots(program, field.type, 0)) catch
            return error.UnsupportedType;
    return slots;
}

fn classFieldStorageOffset(program: Ir.Program, structure_index: usize, field_index: usize) Error!usize {
    if (structure_index >= program.structures.len or field_index >= program.structures[structure_index].fields.len)
        return error.InvalidProgram;
    var slots: usize = 0;
    for (program.structures[structure_index].fields[0..field_index]) |field|
        slots = std.math.add(usize, slots, try llvmStorageSlots(program, field.type, 0)) catch
            return error.UnsupportedType;
    return slots;
}

fn optionalPayloadType(program: Ir.Program, type_value: Ir.Type, depth: usize) bool {
    if (depth >= program.structures.len + 8) return false;
    if (type_value.optionalChild()) |child|
        return optionalPayloadType(program, child, depth + 1);
    if (type_value.isNumeric() or type_value == .bool or type_value == .address) return true;
    return classType(program, type_value);
}

fn closureEnvironmentType(
    allocator: Allocator,
    program: Ir.Program,
    capture_types: []const Ir.Type,
) Error![]const u8 {
    if (capture_types.len == 0) return error.InvalidProgram;
    var output: std.ArrayList(u8) = .empty;
    try output.appendSlice(allocator, "{ ");
    for (capture_types, 0..) |type_value, index| {
        if (index != 0) try output.appendSlice(allocator, ", ");
        try output.appendSlice(allocator, try llvmType(allocator, program, type_value));
    }
    try output.appendSlice(allocator, " }");
    return output.toOwnedSlice(allocator);
}

fn llvmType(allocator: Allocator, program: Ir.Program, type_value: Ir.Type) Error![]const u8 {
    if (type_value.optionalChild()) |child| {
        if (child == .void) return error.UnsupportedType;
        return std.fmt.allocPrint(allocator, "{{ i1, {s} }}", .{try llvmType(allocator, program, child)});
    }
    if (type_value.functionIndex()) |function_type| {
        if (function_type >= program.function_types.len) return error.InvalidProgram;
        return "{ ptr, ptr, ptr }";
    }
    if (type_value.structureIndex()) |structure_index| {
        if (structure_index >= program.structures.len) return error.InvalidProgram;
        if (enumIndexForStructure(program, structure_index)) |enumeration_index| {
            if (plainTagEnum(program, enumeration_index)) return "i64";
            if ((try rawEnumType(program, enumeration_index)) != null)
                return std.fmt.allocPrint(allocator, "%sx.enum.{d}", .{enumeration_index});
            _ = try enumPayloadStorageSlots(program, enumeration_index, 0);
            return std.fmt.allocPrint(allocator, "%sx.enum.{d}", .{enumeration_index});
        }
        if (program.structures[structure_index].is_class) return "ptr";
        if (program.structures[structure_index].is_protocol) {
            _ = try protocolPayloadStorageSlots(program, structure_index, 0);
            return std.fmt.allocPrint(allocator, "%sx.protocol.{d}", .{structure_index});
        }
        if (program.structures[structure_index].is_static)
            return error.UnsupportedType;
        return std.fmt.allocPrint(allocator, "%sx.type.{d}", .{structure_index});
    }
    return switch (type_value) {
        .void => "void",
        .bool => "i1",
        .int8, .uint8 => "i8",
        .int16, .uint16 => "i16",
        .int32, .uint32 => "i32",
        .int, .uint => "i64",
        .float32 => "float",
        .float64 => "double",
        .str => "ptr",
        .address => "ptr",
        else => error.UnsupportedType,
    };
}

fn normalize(bits: u64, type_value: Ir.Type) u64 {
    const width = type_value.bitWidth();
    if (width == 64) return bits;
    return bits & ((@as(u64, 1) << @intCast(width)) - 1);
}

fn integerMinimum(type_value: Ir.Type) i128 {
    if (!type_value.isSignedInteger()) return 0;
    return -(@as(i128, 1) << @intCast(type_value.bitWidth() - 1));
}

fn integerMaximum(type_value: Ir.Type) i128 {
    return if (type_value.isSignedInteger())
        (@as(i128, 1) << @intCast(type_value.bitWidth() - 1)) - 1
    else
        (@as(i128, 1) << @intCast(type_value.bitWidth())) - 1;
}

fn appendFmt(
    output: *std.ArrayList(u8),
    allocator: Allocator,
    comptime format: []const u8,
    arguments: anytype,
) Allocator.Error!void {
    try output.appendSlice(allocator, try std.fmt.allocPrint(allocator, format, arguments));
}

fn emitSourceFiles(output: *std.ArrayList(u8), allocator: Allocator, program: Ir.Program) Allocator.Error!void {
    for (program.files, 0..) |path, index| {
        try appendFmt(output, allocator, "@sx.file.{d} = private constant [{d} x i8] c\"", .{ index, path.len + 1 });
        for (path) |byte| try appendFmt(output, allocator, "\\{X:0>2}", .{byte});
        try output.appendSlice(allocator, "\\00\"\n");
    }
}

fn emitStringLiterals(
    output: *std.ArrayList(u8),
    allocator: Allocator,
    program: Ir.Program,
    functions: []const ?Ir.Function,
) Error!void {
    var emitted = false;
    for (program.enums, 0..) |enumeration, enumeration_index| {
        if (enumeration.raw_type != .str) continue;
        for (enumeration.variants, 0..) |variant, variant_index| {
            const raw_value = variant.raw_value orelse return error.InvalidProgram;
            const value = switch (raw_value) {
                .string => |string| string,
                .integer => return error.InvalidProgram,
            };
            try appendFmt(output, allocator, "@sx.enum.raw.{d}.{d} = private constant {{ i64, [{d} x i8] }} {{ i64 {d}, [{d} x i8] ", .{
                enumeration_index,
                variant_index,
                value.len,
                value.len,
                value.len,
            });
            if (value.len == 0) {
                try output.appendSlice(allocator, "zeroinitializer");
            } else {
                try output.appendSlice(allocator, "c\"");
                try appendEscapedBytes(output, allocator, value);
                try output.append(allocator, '"');
            }
            try output.appendSlice(allocator, " }\n");
            emitted = true;
        }
    }
    for (functions, 0..) |maybe_function, function_id| {
        const function = maybe_function orelse continue;
        for (function.blocks, 0..) |block, block_id| for (block.instructions, 0..) |instruction, instruction_index| switch (instruction) {
            .constant_str => |value| {
                try appendFmt(output, allocator, "@sx.string.{d}.{d}.{d} = private constant {{ i64, [{d} x i8] }} {{ i64 {d}, [{d} x i8] ", .{
                    function_id,
                    block_id,
                    instruction_index,
                    value.value.len,
                    value.value.len,
                    value.value.len,
                });
                if (value.value.len == 0) {
                    try output.appendSlice(allocator, "zeroinitializer");
                } else {
                    try output.appendSlice(allocator, "c\"");
                    try appendEscapedBytes(output, allocator, value.value);
                    try output.append(allocator, '"');
                }
                try output.appendSlice(allocator, " }\n");
                emitted = true;
            },
            .constant_bytes => |value| {
                try appendFmt(output, allocator, "@sx.bytes.{d}.{d}.{d} = private constant [{d} x i8] ", .{
                    function_id,
                    block_id,
                    instruction_index,
                    value.value.len,
                });
                if (value.value.len == 0) {
                    try output.appendSlice(allocator, "zeroinitializer");
                } else {
                    try output.appendSlice(allocator, "c\"");
                    try appendEscapedBytes(output, allocator, value.value);
                    try output.append(allocator, '"');
                }
                try output.append(allocator, '\n');
                emitted = true;
            },
            else => {},
        };
    }
    if (emitted) try output.append(allocator, '\n');
}

fn appendEscapedBytes(output: *std.ArrayList(u8), allocator: Allocator, bytes: []const u8) Allocator.Error!void {
    const digits = "0123456789ABCDEF";
    for (bytes) |byte| {
        try output.append(allocator, '\\');
        try output.append(allocator, digits[byte >> 4]);
        try output.append(allocator, digits[byte & 0x0f]);
    }
}

fn reachableUsesMutex(program: Ir.Program, reachable: []const bool) bool {
    for (program.functions, 0..) |function, function_id| {
        if (!reachable[function_id]) continue;
        for (function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
            .mutex_lock, .mutex_unlock => return true,
            else => {},
        };
    }
    return false;
}

