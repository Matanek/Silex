        });
    }

    fn emitDeepCopy(self: *FunctionEmitter, result: Ir.ValueId, operand: Ir.ValueId) Error!void {
        const type_value = try self.valueType(result);
        if (type_value != try self.valueType(operand)) return error.InvalidProgram;
        const collection = self.collectionInfo(type_value) catch return self.copyValue(result, operand);
        if (collection.view or !plainValue(self.program, collection.element, 0))
            return error.UnsupportedType;

        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, type_value);
        try self.write("  %t{d}.source = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, operand });
        try self.write("  %t{d}.count = extractvalue {s} %v{d}, 1\n", .{ serial, type_name, operand });
        try self.emitCollectionBytes(serial, collection.element);
        try self.write("  %t{d}.storage = call fastcc ptr @sx_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
        try self.write(
            "  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.storage, ptr %t{d}.source, i64 %t{d}.bytes, i1 false)\n",
            .{ serial, serial, serial },
        );
        try self.write("  %t{d}.collection = insertvalue {s} poison, ptr %t{d}.storage, 0\n", .{
            serial,
            type_name,
            serial,
        });
        try self.write("  %v{d} = insertvalue {s} %t{d}.collection, i64 %t{d}.count, 1\n", .{
            result,
            type_name,
            serial,
            serial,
        });
    }

    fn emitStructureInit(self: *FunctionEmitter, value: Ir.Instruction.StructureInit) Error!void {
        if (value.structure >= self.program.structures.len) return error.InvalidProgram;
        const structure = self.program.structures[value.structure];
        if (structure.is_class) return self.emitClassInit(value);
        if (structure.is_static or structure.is_protocol)
            return error.UnsupportedInstruction;
        if (value.fields.len != structure.fields.len or try self.valueType(value.result) != Ir.Type.structure(value.structure))
            return error.InvalidProgram;
        const type_name = try llvmType(self.allocator, self.program, Ir.Type.structure(value.structure));
        if (value.fields.len == 0) {
            try self.write("  %v{d} = freeze {s} poison\n", .{ value.result, type_name });
            return;
        }
        const serial = self.nextTemporary();
        for (value.fields, 0..) |field, field_index| {
            if (try self.valueType(field) != structure.fields[field_index].type) return error.InvalidProgram;
            if (field_index + 1 == value.fields.len)
                try self.write("  %v{d} = insertvalue {s} {s}, {s} %v{d}, {d}\n", .{
                    value.result,
                    type_name,
                    if (field_index == 0) "poison" else try std.fmt.allocPrint(self.allocator, "%t{d}.aggregate{d}", .{ serial, field_index - 1 }),
                    try llvmType(self.allocator, self.program, structure.fields[field_index].type),
                    field,
                    field_index,
                })
            else
                try self.write("  %t{d}.aggregate{d} = insertvalue {s} {s}, {s} %v{d}, {d}\n", .{
                    serial,
                    field_index,
                    type_name,
                    if (field_index == 0) "poison" else try std.fmt.allocPrint(self.allocator, "%t{d}.aggregate{d}", .{ serial, field_index - 1 }),
                    try llvmType(self.allocator, self.program, structure.fields[field_index].type),
                    field,
                    field_index,
                });
        }
    }

    fn emitProtocolInit(self: *FunctionEmitter, value: Ir.Instruction.ProtocolInit) Error!void {
        if (value.structure >= self.program.structures.len or
            try self.valueType(value.operand) != Ir.Type.structure(value.structure))
            return error.InvalidProgram;
        const protocol_index = (try self.valueType(value.result)).structureIndex() orelse
            return error.InvalidProgram;
        if (protocol_index >= self.program.structures.len or
            !self.program.structures[protocol_index].is_protocol or
            !irConforms(self.program, value.structure, protocol_index))
            return error.InvalidProgram;
        _ = try protocolPayloadStorageSlots(self.program, protocol_index, 0);
        const serial = self.nextTemporary();
        const protocol_type = try llvmType(self.allocator, self.program, try self.valueType(value.result));
        const concrete_type = try llvmType(self.allocator, self.program, try self.valueType(value.operand));
        try self.write("  %t{d}.protocol = alloca {s}\n", .{ serial, protocol_type });
        try self.write("  store {s} zeroinitializer, ptr %t{d}.protocol\n", .{ protocol_type, serial });
        if (self.program.structures[value.structure].is_class) {
            try self.write("  %t{d}.protocol.class.tag = load i64, ptr %v{d}\n", .{ serial, value.operand });
            try self.write("  store i64 %t{d}.protocol.class.tag, ptr %t{d}.protocol\n", .{ serial, serial });
        } else {
            try self.write("  store i64 {d}, ptr %t{d}.protocol\n", .{ value.structure, serial });
        }
        try self.write("  %t{d}.protocol.payload = getelementptr i8, ptr %t{d}.protocol, i64 8\n", .{ serial, serial });
        try self.write("  store {s} %v{d}, ptr %t{d}.protocol.payload\n", .{ concrete_type, value.operand, serial });
        try self.write("  %v{d} = load {s}, ptr %t{d}.protocol\n", .{ value.result, protocol_type, serial });
    }

    fn emitProtocolTest(self: *FunctionEmitter, value: Ir.Instruction.ProtocolTest) Error!void {
        if (value.structure >= self.program.structures.len or try self.valueType(value.result) != .bool)
            return error.InvalidProgram;
        const protocol_index = (try self.valueType(value.operand)).structureIndex() orelse
            return error.InvalidProgram;
        if (protocol_index >= self.program.structures.len or
            !self.program.structures[protocol_index].is_protocol or
            !irConforms(self.program, value.structure, protocol_index))
            return error.InvalidProgram;
        const protocol_type = try llvmType(self.allocator, self.program, try self.valueType(value.operand));
        const serial = self.nextTemporary();
        try self.write("  %t{d}.protocol.tag = extractvalue {s} %v{d}, 0\n", .{ serial, protocol_type, value.operand });
        try self.write("  %v{d} = icmp eq i64 %t{d}.protocol.tag, {d}\n", .{ value.result, serial, value.structure });
    }

    fn emitProtocolExtract(self: *FunctionEmitter, value: Ir.Instruction.ProtocolExtract) Error!void {
        if (value.structure >= self.program.structures.len or
            try self.valueType(value.result) != Ir.Type.structure(value.structure))
            return error.InvalidProgram;
        const protocol_index = (try self.valueType(value.operand)).structureIndex() orelse
            return error.InvalidProgram;
        if (protocol_index >= self.program.structures.len or
            !self.program.structures[protocol_index].is_protocol or
            !irConforms(self.program, value.structure, protocol_index))
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        const protocol_type = try llvmType(self.allocator, self.program, try self.valueType(value.operand));
        const concrete_type = try llvmType(self.allocator, self.program, try self.valueType(value.result));
        try self.write("  %t{d}.protocol = alloca {s}\n", .{ serial, protocol_type });
        try self.write("  store {s} %v{d}, ptr %t{d}.protocol\n", .{ protocol_type, value.operand, serial });
        try self.write("  %t{d}.protocol.payload = getelementptr i8, ptr %t{d}.protocol, i64 8\n", .{ serial, serial });
        try self.write("  %v{d} = load {s}, ptr %t{d}.protocol.payload\n", .{ value.result, concrete_type, serial });
    }

    fn emitClassInit(self: *FunctionEmitter, value: Ir.Instruction.StructureInit) Error!void {
        if (!materialClassStorage(self.program, value.structure)) return error.UnsupportedType;
        const structure = self.program.structures[value.structure];
        if (value.fields.len != structure.fields.len or
            try self.valueType(value.result) != Ir.Type.structure(value.structure))
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        const field_bytes = std.math.mul(usize, try classStorageSlots(self.program, value.structure), 8) catch
            return error.UnsupportedType;
        try self.write("  %v{d} = call fastcc ptr @sx_typed_class_alloc(i64 {d}, i64 {d})\n", .{
            value.result,
            field_bytes,
            value.structure,
        });
        for (value.fields, 0..) |field, field_index| {
            if (try self.valueType(field) != structure.fields[field_index].type)
                return error.InvalidProgram;
            try self.write("  %t{d}.class.field{d} = getelementptr i8, ptr %v{d}, i64 {d}\n", .{
                serial,
                field_index,
                value.result,
                8 * (4 + try classFieldStorageOffset(self.program, value.structure, field_index)),
            });
            try self.write("  store {s} %v{d}, ptr %t{d}.class.field{d}\n", .{
                try llvmType(self.allocator, self.program, structure.fields[field_index].type),
                field,
                serial,
                field_index,
            });
        }
    }

    fn emitClassRetain(self: *FunctionEmitter, value: Ir.Instruction.ClassRetain) Error!void {
        const type_value = try self.valueType(value.operand);
        if (type_value.functionIndex()) |signature| {
            if (signature >= self.program.function_types.len) return error.InvalidProgram;
            // The LLVM subset rejects every captured function reference, so
            // its remaining callback value is only a non-owning code pointer.
            return;
        }
        const structure = type_value.structureIndex() orelse return error.InvalidProgram;
        if (!materialClassStorage(self.program, structure))
            return error.UnsupportedInstruction;
        try self.write("  call fastcc void @sx_typed_class_retain(ptr %v{d}, i64 {d})\n", .{
            value.operand,
            if (value.ownership == .root) @as(u8, 8) else 16,
        });
    }

    fn emitClassDrop(self: *FunctionEmitter, value: Ir.Instruction.ClassDrop) Error!void {
        const type_value = try self.valueType(value.operand);
        if (type_value.functionIndex()) |signature| {
            if (signature >= self.program.function_types.len) return error.InvalidProgram;
            // See emitClassRetain: capture-free code pointers own no runtime
            // environment and therefore have no lifetime action to emit.
            return;
        }
        const structure = type_value.structureIndex() orelse return error.InvalidProgram;
        if (structure != value.static_type or !materialClassStorage(self.program, structure) or value.plans.len == 0)
            return error.UnsupportedInstruction;
        for (value.plans) |plan| {
            if (plan.structure >= self.program.structures.len or
                !materialClassStorage(self.program, plan.structure)) return error.UnsupportedInstruction;
            for (plan.functions) |finalizer| {
                if (finalizer.structure != plan.structure or finalizer.function >= self.program.functions.len)
                    return error.InvalidProgram;
                const function = self.program.functions[finalizer.function];
                if (function.capture_types.len != 0 or function.parameter_types.len != 1 or
                    function.parameter_types[0] != Ir.Type.structure(plan.structure) or
                    function.return_type != .void) return error.InvalidProgram;
            }
        }
        const serial = self.nextTemporary();
        try self.write("  %t{d}.class.finalize = call fastcc i1 @sx_typed_class_release(ptr %v{d}, i64 {d})\n", .{
            serial,
            value.operand,
            if (value.ownership == .root) @as(u8, 8) else 16,
        });
        try self.write("  br i1 %t{d}.class.finalize, label %class.finalize{d}, label %class.done{d}\n", .{
            serial,
            serial,
            serial,
        });
        try self.write("class.finalize{d}:\n", .{serial});
        try self.write("  %t{d}.class.type = load i64, ptr %v{d}\n", .{ serial, value.operand });
        try self.write("  switch i64 %t{d}.class.type, label %trap [\n", .{serial});
        for (value.plans, 0..) |plan, plan_index|
            try self.write("    i64 {d}, label %class.plan{d}.{d}\n", .{ plan.structure, serial, plan_index });
        try self.write("  ]\n", .{});
        for (value.plans, 0..) |plan, plan_index| {
            try self.write("class.plan{d}.{d}:\n", .{ serial, plan_index });
            for (plan.functions) |finalizer|
                try self.write("  call fastcc void @sx_{d}(ptr null, ptr %v{d})\n", .{ finalizer.function, value.operand });
            try self.write("  call fastcc void @sx_typed_class_free(ptr %v{d})\n", .{value.operand});
            try self.write("  br label %class.done{d}\n", .{serial});
        }
        try self.write("class.done{d}:\n", .{serial});
    }

    fn emitFieldLoad(self: *FunctionEmitter, value: Ir.Instruction.FieldLoad) Error!void {
        const base_type = try self.valueType(value.base);
        const structure_index = base_type.structureIndex() orelse return error.InvalidProgram;
        if (structure_index >= self.program.structures.len or value.field >= self.program.structures[structure_index].fields.len)
            return error.InvalidProgram;
        if (self.program.structures[structure_index].is_class)
            return self.emitClassFieldLoad(value, structure_index);
        if (try self.valueType(value.result) != self.program.structures[structure_index].fields[value.field].type)
            return error.InvalidProgram;
        try self.write("  %v{d} = extractvalue {s} %v{d}, {d}\n", .{
            value.result,
            try llvmType(self.allocator, self.program, base_type),
            value.base,
            value.field,
        });
    }

    fn emitClassFieldLoad(
        self: *FunctionEmitter,
        value: Ir.Instruction.FieldLoad,
        structure_index: usize,
    ) Error!void {
        if (!materialClassStorage(self.program, structure_index)) return error.UnsupportedType;
        const serial = self.nextTemporary();
        const field_type = self.program.structures[structure_index].fields[value.field].type;
        try self.write("  %t{d}.class.field = getelementptr i8, ptr %v{d}, i64 {d}\n", .{
            serial,
            value.base,
            8 * (4 + try classFieldStorageOffset(self.program, structure_index, value.field)),
        });
        try self.write("  %v{d} = load {s}, ptr %t{d}.class.field\n", .{
            value.result,
            try llvmType(self.allocator, self.program, field_type),
            serial,
        });
    }

    fn emitFieldStore(self: *FunctionEmitter, value: Ir.Instruction.FieldStore) Error!void {
        const base_type = try self.valueType(value.base);
        const structure_index = base_type.structureIndex() orelse return error.InvalidProgram;
        if (structure_index >= self.program.structures.len) return error.InvalidProgram;
        const structure = self.program.structures[structure_index];
        if (!structure.is_class or value.field >= structure.fields.len or
            try self.valueType(value.result) != base_type or
            try self.valueType(value.replacement) != structure.fields[value.field].type)
        {
            return error.InvalidProgram;
        }
        if (!materialClassStorage(self.program, structure_index)) return error.UnsupportedType;
        const serial = self.nextTemporary();
        const field_type = structure.fields[value.field].type;
        try self.write("  %t{d}.class.store.field = getelementptr i8, ptr %v{d}, i64 {d}\n", .{
            serial,
            value.base,
            8 * (4 + try classFieldStorageOffset(self.program, structure_index, value.field)),
        });
        try self.write("  store {s} %v{d}, ptr %t{d}.class.store.field\n", .{
            try llvmType(self.allocator, self.program, field_type),
            value.replacement,
            serial,
        });
        try self.copyValue(value.result, value.base);
    }

    fn emitListInit(self: *FunctionEmitter, value: Ir.Instruction.ListInit) Error!void {
        const type_value = try self.valueType(value.result);
        const collection = try self.collectionInfo(type_value);
        if (collection.view or collection.length != null) return error.UnsupportedType;
        const element_name = try llvmType(self.allocator, self.program, collection.element);
        const type_name = try llvmType(self.allocator, self.program, type_value);
        const serial = self.nextTemporary();
        try self.write("  %t{d}.count = add i64 0, {d}\n", .{ serial, value.values.len });
        try self.emitCollectionBytes(serial, collection.element);
        // A literal can escape its creating function. Its allocation is owned
        // by the retains/drops present in the composed Silex IR.
        try self.write("  %t{d}.storage = call fastcc ptr @sx_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
        for (value.values, 0..) |item, index| {
            if (try self.valueType(item) != collection.element) return error.InvalidProgram;
            try self.write("  %t{d}.item{d} = getelementptr {s}, ptr %t{d}.storage, i64 {d}\n", .{
                serial, index, element_name, serial, index,
            });
            try self.write("  store {s} %v{d}, ptr %t{d}.item{d}\n", .{ element_name, item, serial, index });
        }
        try self.write("  %t{d}.collection = insertvalue {s} poison, ptr %t{d}.storage, 0\n", .{
            serial,
            type_name,
            serial,
        });
        try self.write("  %v{d} = insertvalue {s} %t{d}.collection, i64 {d}, 1\n", .{
            value.result,
            type_name,
            serial,
            value.values.len,
        });
    }

    fn emitListEdit(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.ListEdit) Error!void {
        const type_value = try self.valueType(value.collection);
        const collection = try self.collectionInfo(type_value);
        const report_element_name = try reportTypeName(self.allocator, self.program, collection.element);
        errdefer std.debug.print(
            "silex LLVM evaluation: unsupported list edit {s}, ownership {s}, view {}, fixed {}, element {s}, plain {}, index {}, argument {}, transferred {}, removed {}\n",
            .{
                @tagName(value.kind),
                @tagName(value.ownership),
                collection.view,
                collection.length != null,
                report_element_name,
                plainValue(self.program, collection.element, 0),
                value.index != null,
                value.argument != null,
                value.argument_transferred,
                value.removed != null,
            },
        );
        if (collection.view or collection.length != null or
            try self.valueType(value.result) != type_value)
            return error.UnsupportedInstruction;
        const argument = switch (value.kind) {
            .clear, .take, .take_last => if (value.argument == null) null else return error.InvalidProgram,
            .append, .insert => value.argument orelse return error.InvalidProgram,
            else => return error.UnsupportedInstruction,
        };
        if (value.kind == .insert or value.kind == .take) {
            if (value.index == null or try self.valueType(value.index.?) != .int) return error.InvalidProgram;
        } else if (value.index != null) return error.InvalidProgram;
        if (value.kind == .take or value.kind == .take_last) {
            const removed = value.removed orelse return error.InvalidProgram;
            if (try self.valueType(removed) != collection.element) return error.InvalidProgram;
        } else if (value.removed != null) return error.InvalidProgram;
        if (argument) |operand| {
            if (try self.valueType(operand) != collection.element) return error.InvalidProgram;
        }
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, type_value);
        // Retains and drops for resource-bearing elements are explicit in the
        // surrounding Silex IR. The list edit moves their material values.
        const element_name = try llvmType(self.allocator, self.program, collection.element);
        try self.write("  %t{d}.old.data = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.collection });
        try self.write("  %t{d}.old.count = extractvalue {s} %v{d}, 1\n", .{ serial, type_name, value.collection });
        if (value.kind == .insert or value.kind == .take) {
            const index = value.index.?;
            try self.write("  %t{d}.index.negative = icmp slt i64 %v{d}, 0\n", .{ serial, index });
            try self.write("  %t{d}.index.wrapped = add i64 %t{d}.old.count, %v{d}\n", .{ serial, serial, index });
            try self.write("  %t{d}.index = select i1 %t{d}.index.negative, i64 %t{d}.index.wrapped, i64 %v{d}\n", .{
                serial,
                serial,
                serial,
                index,
            });
            try self.write("  %t{d}.index.low = icmp slt i64 %t{d}.index, 0\n", .{ serial, serial });
            try self.write("  %t{d}.index.high = icmp {s} i64 %t{d}.index, %t{d}.old.count\n", .{
                serial,
                if (value.kind == .insert) "sgt" else "sge",
                serial,
                serial,
            });
            try self.write("  %t{d}.index.invalid = or i1 %t{d}.index.low, %t{d}.index.high\n", .{ serial, serial, serial });
            try self.write("  br i1 %t{d}.index.invalid, label %b{d}.index.fail{d}, label %b{d}.index.cont{d}\n", .{
                serial,
                block_id,
                serial,
                block_id,
                serial,
            });
            try self.write("b{d}.index.fail{d}:\n", .{ block_id, serial });
            try self.write("  call fastcc void @sx_bounds(ptr @sx.file.{d}, i64 {d}, i64 {d}, i64 %v{d}, i64 %t{d}.old.count)\n", .{
                value.position.file,
                value.position.line,
                value.position.column,
                index,
                serial,
            });
            try self.write("  unreachable\nb{d}.index.cont{d}:\n", .{ block_id, serial });
        }
        if (argument != null) {
            try self.write("  %t{d}.count.checked = call {{ i64, i1 }} @llvm.uadd.with.overflow.i64(i64 %t{d}.old.count, i64 1)\n", .{ serial, serial });
            try self.write("  %t{d}.count = extractvalue {{ i64, i1 }} %t{d}.count.checked, 0\n", .{ serial, serial });
            try self.write("  %t{d}.count.overflow = extractvalue {{ i64, i1 }} %t{d}.count.checked, 1\n", .{ serial, serial });
            try self.write("  br i1 %t{d}.count.overflow, label %trap, label %b{d}.list{d}\n", .{ serial, block_id, serial });
            try self.write("b{d}.list{d}:\n", .{ block_id, serial });
        } else if (value.kind == .take or value.kind == .take_last) {
            if (value.kind == .take) {
                try self.write("  %t{d}.count = sub i64 %t{d}.old.count, 1\n", .{ serial, serial });
                return self.emitListTake(value, serial, type_name, element_name, collection.element);
            }
            try self.write("  %t{d}.empty = icmp eq i64 %t{d}.old.count, 0\n", .{ serial, serial });
            try self.write("  br i1 %t{d}.empty, label %b{d}.take.fail{d}, label %b{d}.take.cont{d}\n", .{
                serial,
                block_id,
                serial,
                block_id,
                serial,
            });
            try self.write("b{d}.take.fail{d}:\n", .{ block_id, serial });
            try self.write("  call fastcc void @sx_bounds(ptr @sx.file.{d}, i64 {d}, i64 {d}, i64 0, i64 %t{d}.old.count)\n", .{
                value.position.file,
                value.position.line,
                value.position.column,
                serial,
            });
            try self.write("  unreachable\nb{d}.take.cont{d}:\n", .{ block_id, serial });
            try self.write("  %t{d}.count = sub i64 %t{d}.old.count, 1\n", .{ serial, serial });
        } else {
            try self.write("  %t{d}.count = add i64 0, 0\n", .{serial});
        }
        try self.emitCollectionBytes(serial, collection.element);
        try self.write("  %t{d}.storage = call fastcc ptr @sx_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
        if (value.ownership == .edge) {
            // The result is written directly back into a class field. Move the
            // fresh allocation's initial root to the edge owned by that field.
            try self.write("  call fastcc void @sx_retain(ptr %t{d}.storage, i64 -16)\n", .{serial});
            try self.write("  call fastcc void @sx_drop(ptr %t{d}.storage, i64 -24)\n", .{serial});
        }
        if (argument) |operand| if (value.kind == .append) {
            try self.write("  %t{d}.old.end = getelementptr {s}, ptr null, i64 %t{d}.old.count\n", .{ serial, element_name, serial });
            try self.write("  %t{d}.old.bytes = ptrtoint ptr %t{d}.old.end to i64\n", .{ serial, serial });
            try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.storage, ptr %t{d}.old.data, i64 %t{d}.old.bytes, i1 false)\n", .{ serial, serial, serial });
            try self.write("  %t{d}.appended = getelementptr {s}, ptr %t{d}.storage, i64 %t{d}.old.count\n", .{ serial, element_name, serial, serial });
            try self.write("  store {s} %v{d}, ptr %t{d}.appended\n", .{ element_name, operand, serial });
        } else {
            try self.write("  %t{d}.prefix.end = getelementptr {s}, ptr null, i64 %t{d}.index\n", .{ serial, element_name, serial });
            try self.write("  %t{d}.prefix.bytes = ptrtoint ptr %t{d}.prefix.end to i64\n", .{ serial, serial });
            try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.storage, ptr %t{d}.old.data, i64 %t{d}.prefix.bytes, i1 false)\n", .{ serial, serial, serial });
            try self.write("  %t{d}.inserted = getelementptr {s}, ptr %t{d}.storage, i64 %t{d}.index\n", .{ serial, element_name, serial, serial });
            try self.write("  store {s} %v{d}, ptr %t{d}.inserted\n", .{ element_name, operand, serial });
            try self.write("  %t{d}.tail.count = sub i64 %t{d}.old.count, %t{d}.index\n", .{ serial, serial, serial });
            try self.write("  %t{d}.tail.end = getelementptr {s}, ptr null, i64 %t{d}.tail.count\n", .{ serial, element_name, serial });
            try self.write("  %t{d}.tail.bytes = ptrtoint ptr %t{d}.tail.end to i64\n", .{ serial, serial });
            try self.write("  %t{d}.tail.source = getelementptr {s}, ptr %t{d}.old.data, i64 %t{d}.index\n", .{ serial, element_name, serial, serial });
            try self.write("  %t{d}.tail.index = add i64 %t{d}.index, 1\n", .{ serial, serial });
            try self.write("  %t{d}.tail.destination = getelementptr {s}, ptr %t{d}.storage, i64 %t{d}.tail.index\n", .{ serial, element_name, serial, serial });
            try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.tail.destination, ptr %t{d}.tail.source, i64 %t{d}.tail.bytes, i1 false)\n", .{ serial, serial, serial });
        } else if (value.kind == .take_last) {
            try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.storage, ptr %t{d}.old.data, i64 %t{d}.bytes, i1 false)\n", .{ serial, serial, serial });
            try self.write("  %t{d}.removed.address = getelementptr {s}, ptr %t{d}.old.data, i64 %t{d}.count\n", .{
                serial,
                element_name,
                serial,
                serial,
            });
            try self.write("  %v{d} = load {s}, ptr %t{d}.removed.address\n", .{
                value.removed.?,
                element_name,
                serial,
            });
        }
        // The semantic IR emits the source list_drop for indexed edits and
        // removals. Append and clear delegate that source release here.
        if (value.kind == .append or value.kind == .clear)
            try self.write("  call fastcc void @sx_drop(ptr %t{d}.old.data, i64 {d})\n", .{
                serial,
                if (value.ownership == .root) @as(i8, -24) else -16,
            });
        try self.write("  %t{d}.collection = insertvalue {s} poison, ptr %t{d}.storage, 0\n", .{ serial, type_name, serial });
        try self.write("  %v{d} = insertvalue {s} %t{d}.collection, i64 %t{d}.count, 1\n", .{ value.result, type_name, serial, serial });
    }

    fn emitListTake(
        self: *FunctionEmitter,
        value: Ir.Instruction.ListEdit,
        serial: usize,
        type_name: []const u8,
        element_name: []const u8,
        element_type: Ir.Type,
    ) Error!void {
        try self.emitCollectionBytes(serial, element_type);
        try self.write("  %t{d}.storage = call fastcc ptr @sx_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
        if (value.ownership == .edge) {
            try self.write("  call fastcc void @sx_retain(ptr %t{d}.storage, i64 -16)\n", .{serial});
            try self.write("  call fastcc void @sx_drop(ptr %t{d}.storage, i64 -24)\n", .{serial});
        }
        try self.write("  %t{d}.prefix.end = getelementptr {s}, ptr null, i64 %t{d}.index\n", .{ serial, element_name, serial });
        try self.write("  %t{d}.prefix.bytes = ptrtoint ptr %t{d}.prefix.end to i64\n", .{ serial, serial });
        try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.storage, ptr %t{d}.old.data, i64 %t{d}.prefix.bytes, i1 false)\n", .{ serial, serial, serial });
        try self.write("  %t{d}.removed.address = getelementptr {s}, ptr %t{d}.old.data, i64 %t{d}.index\n", .{
            serial,
            element_name,
            serial,
            serial,
        });
        try self.write("  %v{d} = load {s}, ptr %t{d}.removed.address\n", .{ value.removed.?, element_name, serial });
        try self.write("  %t{d}.tail.count.with.removed = sub i64 %t{d}.old.count, %t{d}.index\n", .{ serial, serial, serial });
        try self.write("  %t{d}.tail.count = sub i64 %t{d}.tail.count.with.removed, 1\n", .{ serial, serial });
        try self.write("  %t{d}.tail.end = getelementptr {s}, ptr null, i64 %t{d}.tail.count\n", .{ serial, element_name, serial });
        try self.write("  %t{d}.tail.bytes = ptrtoint ptr %t{d}.tail.end to i64\n", .{ serial, serial });
        try self.write("  %t{d}.tail.source.index = add i64 %t{d}.index, 1\n", .{ serial, serial });
        try self.write("  %t{d}.tail.source = getelementptr {s}, ptr %t{d}.old.data, i64 %t{d}.tail.source.index\n", .{ serial, element_name, serial, serial });
        try self.write("  %t{d}.tail.destination = getelementptr {s}, ptr %t{d}.storage, i64 %t{d}.index\n", .{ serial, element_name, serial, serial });
        try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.tail.destination, ptr %t{d}.tail.source, i64 %t{d}.tail.bytes, i1 false)\n", .{ serial, serial, serial });
        try self.write("  %t{d}.collection = insertvalue {s} poison, ptr %t{d}.storage, 0\n", .{ serial, type_name, serial });
        try self.write("  %v{d} = insertvalue {s} %t{d}.collection, i64 %t{d}.count, 1\n", .{ value.result, type_name, serial, serial });
    }

    fn emitCollectionCount(self: *FunctionEmitter, value: Ir.Instruction.CollectionCount) Error!void {
        const collection_type = try self.valueType(value.collection);
        const collection = try self.collectionInfo(collection_type);
        if (try self.valueType(value.result) != .int) return error.InvalidProgram;
        if (collection.length) |length| {
            try self.write("  %v{d} = add i64 0, {d}\n", .{ value.result, length });
            return;
        }
        try self.write("  %v{d} = extractvalue {s} %v{d}, 1\n", .{
            value.result,
            try llvmType(self.allocator, self.program, collection_type),
            value.collection,
        });
    }

    fn emitCollectionLoad(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.CollectionLoad) Error!void {
        const collection_type = try self.valueType(value.collection);
        const collection = try self.collectionInfo(collection_type);
        if (try self.valueType(value.index) != .int or try self.valueType(value.result) != collection.element)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, collection_type);
        const element_name = try llvmType(self.allocator, self.program, collection.element);
        if (collection.length) |length| {
            try self.write("  %t{d}.storage = alloca {s}\n", .{ serial, type_name });
            try self.write("  store {s} %v{d}, ptr %t{d}.storage\n", .{ type_name, value.collection, serial });
            try self.write("  %t{d}.count = add i64 0, {d}\n", .{ serial, length });
        } else {
            try self.write("  %t{d}.data = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.collection });
            try self.write("  %t{d}.count = extractvalue {s} %v{d}, 1\n", .{ serial, type_name, value.collection });
        }
        try self.emitNormalizedIndex(serial, "index", value.index);
        if (value.checked) {
            try self.write("  %t{d}.index.low = icmp slt i64 %t{d}.index, 0\n", .{ serial, serial });
            try self.write("  %t{d}.index.high = icmp sge i64 %t{d}.index, %t{d}.count\n", .{ serial, serial, serial });
            try self.write("  %t{d}.index.invalid = or i1 %t{d}.index.low, %t{d}.index.high\n", .{ serial, serial, serial });
            try self.emitBoundsFailure(block_id, serial, value.index, value.position);
        }
        if (collection.length != null)
            try self.write("  %t{d}.element = getelementptr {s}, ptr %t{d}.storage, i32 0, i64 %t{d}.index\n", .{ serial, type_name, serial, serial })
        else
            try self.write("  %t{d}.element = getelementptr {s}, ptr %t{d}.data, i64 %t{d}.index\n", .{ serial, element_name, serial, serial });
        try self.write("  %v{d} = load {s}, ptr %t{d}.element\n", .{ value.result, element_name, serial });
    }

    fn emitCollectionReference(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.CollectionReference) Error!void {
        const collection_type = try self.valueType(value.collection);
        const collection = try self.collectionInfo(collection_type);
        const element_name = try reportTypeName(self.allocator, self.program, collection.element);
        errdefer std.debug.print(
            "silex LLVM evaluation: unsupported collection reference, view {}, ownership {s}, mutable source {}, element {s}\n",
            .{ collection.view, @tagName(value.ownership), value.reference != null, element_name },
        );
        _ = try llvmType(self.allocator, self.program, collection.element);
        if (try self.valueType(value.index) != .int or try self.valueType(value.result) != .address)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, collection_type);
        if (collection.length) |length| {
            try self.write("  %t{d}.count = add i64 0, {d}\n", .{ serial, length });
            const storage = if (value.reference) |reference| fixed: {
                if (try self.valueType(reference) != .address) return error.InvalidProgram;
                break :fixed try std.fmt.allocPrint(self.allocator, "%v{d}", .{reference});
            } else fixed: {
                try self.write("  %t{d}.storage = alloca {s}\n", .{ serial, type_name });
                try self.write("  store {s} %v{d}, ptr %t{d}.storage\n", .{ type_name, value.collection, serial });
                break :fixed try std.fmt.allocPrint(self.allocator, "%t{d}.storage", .{serial});
            };
            try self.emitNormalizedIndex(serial, "index", value.index);
            if (value.checked) {
                try self.write("  %t{d}.index.low = icmp slt i64 %t{d}.index, 0\n", .{ serial, serial });
                try self.write("  %t{d}.index.high = icmp sge i64 %t{d}.index, %t{d}.count\n", .{ serial, serial, serial });
                try self.write("  %t{d}.index.invalid = or i1 %t{d}.index.low, %t{d}.index.high\n", .{ serial, serial, serial });
                try self.emitBoundsFailure(block_id, serial, value.index, value.position);
            }
            try self.write("  %v{d} = getelementptr {s}, ptr {s}, i32 0, i64 %t{d}.index\n", .{
                value.result, type_name, storage, serial,
            });
            return;
        }
        if (!collection.view and value.reference != null) {
            const reference = value.reference.?;
            if (try self.valueType(reference) != .address) return error.InvalidProgram;
            try self.write("  %t{d}.source = load {s}, ptr %v{d}\n", .{ serial, type_name, reference });
            try self.write("  %t{d}.old.data = extractvalue {s} %t{d}.source, 0\n", .{ serial, type_name, serial });
            try self.write("  %t{d}.count = extractvalue {s} %t{d}.source, 1\n", .{ serial, type_name, serial });
            try self.write("  %t{d}.roots.address = getelementptr i8, ptr %t{d}.old.data, i64 -24\n", .{ serial, serial });
            try self.write("  %t{d}.roots = load atomic i64, ptr %t{d}.roots.address acquire, align 8\n", .{ serial, serial });
            try self.write("  %t{d}.edges.address = getelementptr i8, ptr %t{d}.old.data, i64 -16\n", .{ serial, serial });
            try self.write("  %t{d}.edges = load atomic i64, ptr %t{d}.edges.address acquire, align 8\n", .{ serial, serial });
            try self.write("  %t{d}.owners = add i64 %t{d}.roots, %t{d}.edges\n", .{ serial, serial, serial });
            try self.write("  %t{d}.shared = icmp ne i64 %t{d}.owners, 1\n", .{ serial, serial });
            try self.write("  br i1 %t{d}.shared, label %collection.detach{d}, label %collection.unique{d}\n", .{ serial, serial, serial });
            try self.write("collection.detach{d}:\n", .{serial});
            try self.emitCollectionBytes(serial, collection.element);
            try self.write("  %t{d}.storage = call fastcc ptr @sx_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
            if (value.ownership == .edge) {
                try self.write("  call fastcc void @sx_retain(ptr %t{d}.storage, i64 -16)\n", .{serial});
                try self.write("  call fastcc void @sx_drop(ptr %t{d}.storage, i64 -24)\n", .{serial});
            }
            try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.storage, ptr %t{d}.old.data, i64 %t{d}.bytes, i1 false)\n", .{ serial, serial, serial });
            try self.write("  %t{d}.detached.data = insertvalue {s} %t{d}.source, ptr %t{d}.storage, 0\n", .{ serial, type_name, serial, serial });
            try self.write("  store {s} %t{d}.detached.data, ptr %v{d}\n", .{ type_name, serial, reference });
            try self.write("  call fastcc void @sx_drop(ptr %t{d}.old.data, i64 {d})\n", .{
                serial,
                if (value.ownership == .root) @as(i8, -24) else -16,
            });
            try self.write("  br label %collection.ready{d}\n", .{serial});
            try self.write("collection.unique{d}:\n", .{serial});
            try self.write("  br label %collection.ready{d}\n", .{serial});
            try self.write("collection.ready{d}:\n", .{serial});
            try self.write("  %t{d}.data = phi ptr [ %t{d}.storage, %collection.detach{d} ], [ %t{d}.old.data, %collection.unique{d} ]\n", .{
                serial,
                serial,
                serial,
                serial,
                serial,
            });
        } else if (value.reference) |reference| {
            if (try self.valueType(reference) != .address) return error.InvalidProgram;
            try self.write("  %t{d}.source = load {s}, ptr %v{d}\n", .{ serial, type_name, reference });
            try self.write("  %t{d}.data = extractvalue {s} %t{d}.source, 0\n", .{ serial, type_name, serial });
            try self.write("  %t{d}.count = extractvalue {s} %t{d}.source, 1\n", .{ serial, type_name, serial });
        } else {
            try self.write("  %t{d}.data = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.collection });
            try self.write("  %t{d}.count = extractvalue {s} %v{d}, 1\n", .{ serial, type_name, value.collection });
        }
        try self.emitNormalizedIndex(serial, "index", value.index);
        if (value.checked) {
            try self.write("  %t{d}.index.low = icmp slt i64 %t{d}.index, 0\n", .{ serial, serial });
            try self.write("  %t{d}.index.high = icmp sge i64 %t{d}.index, %t{d}.count\n", .{ serial, serial, serial });
            try self.write("  %t{d}.index.invalid = or i1 %t{d}.index.low, %t{d}.index.high\n", .{ serial, serial, serial });
            try self.emitBoundsFailure(block_id, serial, value.index, value.position);
        }
        try self.write("  %v{d} = getelementptr {s}, ptr %t{d}.data, i64 %t{d}.index\n", .{
            value.result, try llvmType(self.allocator, self.program, collection.element), serial, serial,
        });
    }

    fn emitCollectionBytes(self: *FunctionEmitter, serial: usize, element: Ir.Type) Error!void {
        // Let LLVM compute its own aggregate padding; Silex's storage slots
        // are not the oracle's layout and cannot be used as a byte stride.
        try self.write("  %t{d}.end = getelementptr {s}, ptr null, i64 %t{d}.count\n", .{
            serial, try llvmType(self.allocator, self.program, element), serial,
        });
        try self.write("  %t{d}.bytes = ptrtoint ptr %t{d}.end to i64\n", .{ serial, serial });
    }

    fn emitCollectionReplace(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.CollectionReplace) Error!void {
        const collection_type = try self.valueType(value.collection);
        const collection = try self.collectionInfo(collection_type);
        const result_type = try self.valueType(value.result);
        const index_type = try self.valueType(value.index);
        const replacement_type = try self.valueType(value.replacement);
        if (result_type != collection_type or
            index_type != .int or
            replacement_type != collection.element)
        {
            std.debug.print(
                "silex LLVM evaluation: unsupported collection replacement collection={s}, result={s}, index={s}, replacement={s}, element={s}\n",
                .{
                    try reportTypeName(self.allocator, self.program, collection_type),
                    try reportTypeName(self.allocator, self.program, result_type),
                    try reportTypeName(self.allocator, self.program, index_type),
                    try reportTypeName(self.allocator, self.program, replacement_type),
                    try reportTypeName(self.allocator, self.program, collection.element),
                },
            );
            return error.UnsupportedInstruction;
        }
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, collection_type);
        const element_name = try llvmType(self.allocator, self.program, collection.element);
        if (collection.length) |length| {
            try self.write("  %t{d}.storage = alloca {s}\n", .{ serial, type_name });
            try self.write("  store {s} %v{d}, ptr %t{d}.storage\n", .{ type_name, value.collection, serial });
            try self.write("  %t{d}.count = add i64 0, {d}\n", .{ serial, length });
            try self.emitNormalizedIndex(serial, "index", value.index);
            if (value.checked) {
                try self.write("  %t{d}.index.low = icmp slt i64 %t{d}.index, 0\n", .{ serial, serial });
                try self.write("  %t{d}.index.high = icmp sge i64 %t{d}.index, %t{d}.count\n", .{ serial, serial, serial });
                try self.write("  %t{d}.index.invalid = or i1 %t{d}.index.low, %t{d}.index.high\n", .{ serial, serial, serial });
                try self.emitBoundsFailure(block_id, serial, value.index, value.position);
            }
            try self.write("  %t{d}.element = getelementptr {s}, ptr %t{d}.storage, i32 0, i64 %t{d}.index\n", .{
                serial, type_name, serial, serial,
            });
            try self.write("  store {s} %v{d}, ptr %t{d}.element\n", .{ element_name, value.replacement, serial });
            try self.write("  %v{d} = load {s}, ptr %t{d}.storage\n", .{ value.result, type_name, serial });
            return;
        }
        try self.write("  %t{d}.data = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.collection });
        try self.write("  %t{d}.count = extractvalue {s} %v{d}, 1\n", .{ serial, type_name, value.collection });
        try self.emitNormalizedIndex(serial, "index", value.index);
        if (value.checked) {
            try self.write("  %t{d}.index.low = icmp slt i64 %t{d}.index, 0\n", .{ serial, serial });
            try self.write("  %t{d}.index.high = icmp sge i64 %t{d}.index, %t{d}.count\n", .{ serial, serial, serial });
            try self.write("  %t{d}.index.invalid = or i1 %t{d}.index.low, %t{d}.index.high\n", .{ serial, serial, serial });
            try self.emitBoundsFailure(block_id, serial, value.index, value.position);
        }
        if (!collection.view) {
            try self.emitCollectionBytes(serial, collection.element);
            try self.write("  %t{d}.copy = call fastcc ptr @sx_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
            if (value.ownership == .edge) {
                try self.write("  call fastcc void @sx_retain(ptr %t{d}.copy, i64 -16)\n", .{serial});
                try self.write("  call fastcc void @sx_drop(ptr %t{d}.copy, i64 -24)\n", .{serial});
            }
            try self.write(
                "  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.copy, ptr %t{d}.data, i64 %t{d}.bytes, i1 false)\n",
                .{ serial, serial, serial },
            );
            // collection_replace transfers the consumed owning storage to its
            // result. Cloning the payload must release that source owner.
            try self.write("  call fastcc void @sx_drop(ptr %t{d}.data, i64 {d})\n", .{
                serial,
                if (value.ownership == .root) @as(i8, -24) else -16,
            });
        }
        try self.write("  %t{d}.element = getelementptr {s}, ptr %t{d}.{s}, i64 %t{d}.index\n", .{
            serial,
            element_name,
            serial,
            if (collection.view) "data" else "copy",
            serial,
        });
        try self.write("  store {s} %v{d}, ptr %t{d}.element\n", .{ element_name, value.replacement, serial });
        if (collection.view) {
            try self.copyValue(value.result, value.collection);
        } else {
            try self.write("  %t{d}.updated = insertvalue {s} poison, ptr %t{d}.copy, 0\n", .{
                serial,
                type_name,
                serial,
            });
            try self.write("  %v{d} = insertvalue {s} %t{d}.updated, i64 %t{d}.count, 1\n", .{
                value.result,
                type_name,
                serial,
                serial,
            });
        }
    }

    fn emitCollectionView(self: *FunctionEmitter, _: usize, value: Ir.Instruction.CollectionSlice) Error!void {
        const source_type = try self.valueType(value.collection);
        const result_type = try self.valueType(value.result);
        const source = try self.collectionInfo(source_type);
        const result = try self.collectionInfo(result_type);
        if (value.reference != null and !source.view and source.length == null) return error.UnsupportedInstruction;
        if (source.element != result.element or !result.view or
            try self.valueType(value.start) != .int or try self.valueType(value.end) != .int)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        const source_name = try llvmType(self.allocator, self.program, source_type);
        const result_name = try llvmType(self.allocator, self.program, result_type);
        const element_name = try llvmType(self.allocator, self.program, source.element);
        if (source.length) |length| {
            if (value.reference) |reference| {
                if (try self.valueType(reference) != .address) return error.InvalidProgram;
                try self.write("  %t{d}.data = getelementptr {s}, ptr %v{d}, i32 0, i32 0\n", .{ serial, source_name, reference });
            } else {
                try self.write("  %t{d}.source = alloca {s}\n", .{ serial, source_name });
                try self.write("  store {s} %v{d}, ptr %t{d}.source\n", .{ source_name, value.collection, serial });
                try self.write("  %t{d}.data = getelementptr {s}, ptr %t{d}.source, i32 0, i32 0\n", .{ serial, source_name, serial });
            }
            try self.write("  %t{d}.count = add i64 0, {d}\n", .{ serial, length });
        } else if (value.reference) |reference| {
            if (try self.valueType(reference) != .address) return error.InvalidProgram;
            try self.write("  %t{d}.source = load {s}, ptr %v{d}\n", .{ serial, source_name, reference });
            try self.write("  %t{d}.data = extractvalue {s} %t{d}.source, 0\n", .{ serial, source_name, serial });
            try self.write("  %t{d}.count = extractvalue {s} %t{d}.source, 1\n", .{ serial, source_name, serial });
        } else {
            try self.write("  %t{d}.data = extractvalue {s} %v{d}, 0\n", .{ serial, source_name, value.collection });
            try self.write("  %t{d}.count = extractvalue {s} %v{d}, 1\n", .{ serial, source_name, value.collection });
        }
        try self.emitClampedSliceBound(serial, "start", value.start);
        try self.emitClampedSliceBound(serial, "end", value.end);
        try self.write("  %t{d}.view.data = getelementptr {s}, ptr %t{d}.data, i64 %t{d}.start.clamped\n", .{
            serial, element_name, serial, serial,
        });
        try self.write("  %t{d}.view.difference = sub i64 %t{d}.end.clamped, %t{d}.start.clamped\n", .{ serial, serial, serial });
        try self.write("  %t{d}.view.nonempty = icmp sgt i64 %t{d}.view.difference, 0\n", .{ serial, serial });
        try self.write("  %t{d}.view.count = select i1 %t{d}.view.nonempty, i64 %t{d}.view.difference, i64 0\n", .{ serial, serial, serial });
        try self.write("  %t{d}.view = insertvalue {s} poison, ptr %t{d}.view.data, 0\n", .{
            serial,
            result_name,
            serial,
        });
        try self.write("  %v{d} = insertvalue {s} %t{d}.view, i64 %t{d}.view.count, 1\n", .{
            value.result,
            result_name,
            serial,
            serial,
        });
    }

    fn emitCollectionSlice(self: *FunctionEmitter, value: Ir.Instruction.CollectionSlice) Error!void {
        const source_type = try self.valueType(value.collection);
        const result_type = try self.valueType(value.result);
        const source = try self.collectionInfo(source_type);
        const result = try self.collectionInfo(result_type);
        if (value.reference != null or source.element != result.element or
            result.view or result.length != null or
            try self.valueType(value.start) != .int or
            try self.valueType(value.end) != .int)
            return error.InvalidProgram;
        if (!plainValue(self.program, source.element, 0)) return error.UnsupportedInstruction;

        const serial = self.nextTemporary();
        const source_name = try llvmType(self.allocator, self.program, source_type);
        const result_name = try llvmType(self.allocator, self.program, result_type);
        const element_name = try llvmType(self.allocator, self.program, source.element);
        if (source.length) |length| {
            try self.write("  %t{d}.source = alloca {s}\n", .{ serial, source_name });
            try self.write("  store {s} %v{d}, ptr %t{d}.source\n", .{ source_name, value.collection, serial });
            try self.write("  %t{d}.data = getelementptr {s}, ptr %t{d}.source, i32 0, i32 0\n", .{ serial, source_name, serial });
            try self.write("  %t{d}.count = add i64 0, {d}\n", .{ serial, length });
        } else {
            try self.write("  %t{d}.data = extractvalue {s} %v{d}, 0\n", .{ serial, source_name, value.collection });
            try self.write("  %t{d}.count = extractvalue {s} %v{d}, 1\n", .{ serial, source_name, value.collection });
        }
        try self.emitClampedSliceBound(serial, "start", value.start);
        try self.emitClampedSliceBound(serial, "end", value.end);
        try self.write("  %t{d}.slice.difference = sub i64 %t{d}.end.clamped, %t{d}.start.clamped\n", .{ serial, serial, serial });
        try self.write("  %t{d}.slice.nonempty = icmp sgt i64 %t{d}.slice.difference, 0\n", .{ serial, serial });
        try self.write("  %t{d}.slice.count = select i1 %t{d}.slice.nonempty, i64 %t{d}.slice.difference, i64 0\n", .{ serial, serial, serial });
        try self.write("  %t{d}.slice.source = getelementptr {s}, ptr %t{d}.data, i64 %t{d}.start.clamped\n", .{ serial, element_name, serial, serial });
        try self.write("  %t{d}.slice.end = getelementptr {s}, ptr null, i64 %t{d}.slice.count\n", .{ serial, element_name, serial });
        try self.write("  %t{d}.bytes = ptrtoint ptr %t{d}.slice.end to i64\n", .{ serial, serial });
        // Slicing lowers with an explicit retain for the produced root. Start
        // at zero so that retain, rather than the allocation site, owns it.
        try self.write("  %t{d}.slice.storage = call fastcc ptr @sx_unowned_alloc(i64 %t{d}.bytes)\n", .{ serial, serial });
        try self.write(
            "  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.slice.storage, ptr %t{d}.slice.source, i64 %t{d}.bytes, i1 false)\n",
            .{ serial, serial, serial },
        );
        try self.write("  %t{d}.slice.value = insertvalue {s} poison, ptr %t{d}.slice.storage, 0\n", .{ serial, result_name, serial });
        try self.write("  %v{d} = insertvalue {s} %t{d}.slice.value, i64 %t{d}.slice.count, 1\n", .{ value.result, result_name, serial, serial });
    }

    fn emitClampedSliceBound(self: *FunctionEmitter, serial: usize, comptime name: []const u8, value: Ir.ValueId) Error!void {
        try self.emitNormalizedIndex(serial, name, value);
        try self.write("  %t{d}.{s}.low = icmp slt i64 %t{d}.{s}, 0\n", .{ serial, name, serial, name });
        try self.write("  %t{d}.{s}.nonnegative = select i1 %t{d}.{s}.low, i64 0, i64 %t{d}.{s}\n", .{ serial, name, serial, name, serial, name });
        try self.write("  %t{d}.{s}.high = icmp sgt i64 %t{d}.{s}.nonnegative, %t{d}.count\n", .{ serial, name, serial, name, serial });
        try self.write("  %t{d}.{s}.clamped = select i1 %t{d}.{s}.high, i64 %t{d}.count, i64 %t{d}.{s}.nonnegative\n", .{ serial, name, serial, name, serial, serial, name });
    }

    fn emitNormalizedIndex(self: *FunctionEmitter, serial: usize, comptime name: []const u8, value: Ir.ValueId) Error!void {
        try self.write("  %t{d}.{s}.negative = icmp slt i64 %v{d}, 0\n", .{ serial, name, value });
        try self.write("  %t{d}.{s}.wrapped = add i64 %t{d}.count, %v{d}\n", .{ serial, name, serial, value });
        try self.write("  %t{d}.{s} = select i1 %t{d}.{s}.negative, i64 %t{d}.{s}.wrapped, i64 %v{d}\n", .{
            serial,
            name,
            serial,
            name,
            serial,
            name,
            value,
        });
    }

    fn collectionInfo(self: *FunctionEmitter, type_value: Ir.Type) Error!CollectionInfo {
        const structure = type_value.structureIndex() orelse return error.UnsupportedType;
        if (structure >= self.program.structures.len) return error.InvalidProgram;
        const collection = self.program.structures[structure].collection orelse return error.UnsupportedType;
        return .{ .element = collection.element, .length = collection.length, .view = collection.view };
    }

    fn emitLocalAddress(self: *FunctionEmitter, value: Ir.Instruction.LocalAddress) Error!void {
        if (value.local >= self.function.local_types.len or try self.valueType(value.result) != .address)
            return error.InvalidProgram;
        try self.write("  %v{d} = getelementptr {s}, ptr %local{d}, i32 0\n", .{
            value.result,
            try llvmType(self.allocator, self.program, self.function.local_types[value.local]),
            value.local,
        });
    }

    fn emitReferenceLoad(self: *FunctionEmitter, value: Ir.Instruction.ReferenceLoad) Error!void {
        if (try self.valueType(value.reference) != .address) return error.InvalidProgram;
        try self.write("  %v{d} = load {s}, ptr %v{d}\n", .{
            value.result,
            try llvmType(self.allocator, self.program, try self.valueType(value.result)),
            value.reference,
        });
    }

    fn emitReferenceStore(self: *FunctionEmitter, value: Ir.Instruction.ReferenceStore) Error!void {
        if (try self.valueType(value.reference) != .address) return error.InvalidProgram;
        try self.write("  store {s} %v{d}, ptr %v{d}\n", .{
            try llvmType(self.allocator, self.program, try self.valueType(value.operand)),
            value.operand,
            value.reference,
        });
    }

    fn emitReferenceField(self: *FunctionEmitter, value: Ir.Instruction.ReferenceField) Error!void {
        if (value.structure >= self.program.structures.len or
            value.field >= self.program.structures[value.structure].fields.len or
            try self.valueType(value.reference) != .address or
            try self.valueType(value.result) != .address)
        {
            return error.InvalidProgram;
        }
        if (self.program.structures[value.structure].is_class) {
            if (!materialClassStorage(self.program, value.structure)) return error.UnsupportedInstruction;
            const serial = self.nextTemporary();
            try self.write("  %t{d}.class = load ptr, ptr %v{d}\n", .{ serial, value.reference });
            try self.write("  %v{d} = getelementptr i8, ptr %t{d}.class, i64 {d}\n", .{
                value.result,
                serial,
                8 * (4 + try classFieldStorageOffset(self.program, value.structure, value.field)),
            });
            return;
        }
        try self.write("  %v{d} = getelementptr {s}, ptr %v{d}, i32 0, i32 {d}\n", .{
            value.result,
            try llvmType(self.allocator, self.program, Ir.Type.structure(value.structure)),
            value.reference,
            value.field,
        });
    }

    fn emitReferenceOptional(self: *FunctionEmitter, value: Ir.Instruction.ReferenceOptional) Error!void {
        if (try self.valueType(value.reference) != .address or try self.valueType(value.result) != .address)
            return error.InvalidProgram;
        const optional_type = try self.referencePointeeType(value.reference, 0);
        if (optional_type.optionalChild() == null) return error.InvalidProgram;
        try self.write("  %v{d} = getelementptr {s}, ptr %v{d}, i32 0, i32 1\n", .{
            value.result,
            try llvmType(self.allocator, self.program, optional_type),
            value.reference,
        });
    }

    fn referencePointeeType(self: *FunctionEmitter, reference: Ir.ValueId, depth: usize) Error!Ir.Type {
        if (depth >= self.function.value_types.len) return error.UnsupportedType;
        for (self.function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
            .local_address => |value| if (value.result == reference) {
                if (value.local >= self.function.local_types.len) return error.InvalidProgram;
                return self.function.local_types[value.local];
            },
            .reference_field => |value| if (value.result == reference) {
                if (value.structure >= self.program.structures.len or
                    value.field >= self.program.structures[value.structure].fields.len)
                    return error.InvalidProgram;
                return self.program.structures[value.structure].fields[value.field].type;
            },
            .collection_reference => |value| if (value.result == reference) {
                return (try self.collectionInfo(try self.valueType(value.collection))).element;
            },
            .reference_optional => |value| if (value.result == reference) {
                return (try self.referencePointeeType(value.reference, depth + 1)).optionalChild() orelse
                    error.InvalidProgram;
            },
            .copy => |value| if (value.result == reference) {
                return self.referencePointeeType(value.operand, depth + 1);
            },
            else => {},
        };
        return error.UnsupportedType;
    }

    fn emitNegate(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Unary) Error!void {
        const type_value = try self.valueType(value.operand);
        if (value.operator != .negate) return error.UnsupportedInstruction;
        if (type_value.isFloat()) return self.write("  %v{d} = fneg {s} %v{d}\n", .{
            value.result,
            try llvmType(self.allocator, self.program, type_value),
            value.operand,
        });
        if (!type_value.isInteger()) return error.UnsupportedInstruction;
        const signed = type_value.isSignedInteger();
        try self.emitOverflowOperation(
            block_id,
            value.result,
            if (signed) "ssub" else "usub",
            type_value,
            "0",
            try std.fmt.allocPrint(self.allocator, "%v{d}", .{value.operand}),
        );
    }

    fn emitBinary(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Binary) Error!void {
        const left_type = try self.valueType(value.left);
        const right_type = try self.valueType(value.right);
        const left_type_name = try reportTypeName(self.allocator, self.program, left_type);
        const right_type_name = try reportTypeName(self.allocator, self.program, right_type);
        errdefer std.debug.print(
            "silex LLVM evaluation: unsupported binary operator {s}, left type {s}, right type {s}\n",
            .{ @tagName(value.operator), left_type_name, right_type_name },
        );
        const shift = value.operator == .shift_left or value.operator == .shift_right;
        if (left_type != right_type and !shift) return error.InvalidProgram;
        if ((value.operator == .equal or value.operator == .not_equal) and
            try self.valueType(value.result) != .bool)
            return error.InvalidProgram;
        if (left_type.optionalChild() != null) return self.emitOptionalEquality(block_id, value, left_type);
        if (left_type == .str) {
            if (value.operator != .equal and value.operator != .not_equal)
                return error.UnsupportedInstruction;
            const serial = self.nextTemporary();
            try self.write("  %t{d}.string.equal = call fastcc i1 @sx_string_equal(ptr %v{d}, ptr %v{d})\n", .{
                serial,
                value.left,
                value.right,
            });
            if (value.operator == .equal)
                return self.write("  %v{d} = xor i1 %t{d}.string.equal, false\n", .{ value.result, serial });
            return self.write("  %v{d} = xor i1 %t{d}.string.equal, true\n", .{ value.result, serial });
        }
        if (plainTagEnumType(self.program, left_type)) {
            if (value.operator != .equal and value.operator != .not_equal)
                return error.UnsupportedInstruction;
            return self.write("  %v{d} = icmp {s} i64 %v{d}, %v{d}\n", .{
                value.result,
                if (value.operator == .equal) "eq" else "ne",
                value.left,
                value.right,
            });
        }
        if (left_type.structureIndex()) |structure_index| {
            if (enumIndexForStructure(self.program, structure_index)) |enumeration_index| {
                if ((try rawEnumType(self.program, enumeration_index)) != null) {
                    if (value.operator != .equal and value.operator != .not_equal)
                        return error.UnsupportedInstruction;
                    const serial = self.nextTemporary();
                    const type_name = try llvmType(self.allocator, self.program, left_type);
                    try self.write("  %t{d}.enum.left.tag = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.left });
                    try self.write("  %t{d}.enum.right.tag = extractvalue {s} %v{d}, 0\n", .{ serial, type_name, value.right });
                    return self.write("  %v{d} = icmp {s} i64 %t{d}.enum.left.tag, %t{d}.enum.right.tag\n", .{
                        value.result,
                        if (value.operator == .equal) "eq" else "ne",
                        serial,
                        serial,
                    });
                }
            }
            if (structure_index >= self.program.structures.len) return error.InvalidProgram;
            if (self.program.structures[structure_index].is_class) {
                if (value.operator != .equal and value.operator != .not_equal)
                    return error.UnsupportedInstruction;
                return self.write("  %v{d} = icmp {s} ptr %v{d}, %v{d}\n", .{
                    value.result,
                    if (value.operator == .equal) "eq" else "ne",
                    value.left,
                    value.right,
                });
            }
            if (plainValue(self.program, left_type, 0))
                return self.emitPlainAggregateEquality(value, left_type);
        }
        const type_name = try llvmType(self.allocator, self.program, left_type);
        switch (value.operator) {
            .add, .subtract, .multiply => {
                if (left_type.isFloat()) return self.write("  %v{d} = {s} {s} %v{d}, %v{d}\n", .{
                    value.result,
                    switch (value.operator) {
                        .add => "fadd",
                        .subtract => "fsub",
                        .multiply => "fmul",
                        else => unreachable,
                    },
                    type_name,
                    value.left,
                    value.right,
                });
                if (!left_type.isInteger()) return error.UnsupportedInstruction;
                const prefix = if (left_type.isSignedInteger()) "s" else "u";
                const operation = switch (value.operator) {
                    .add => "add",
                    .subtract => "sub",
                    .multiply => "mul",
                    else => unreachable,
                };
                try self.emitOverflowOperation(
                    block_id,
                    value.result,
                    try std.fmt.allocPrint(self.allocator, "{s}{s}", .{ prefix, operation }),
                    left_type,
                    try std.fmt.allocPrint(self.allocator, "%v{d}", .{value.left}),
                    try std.fmt.allocPrint(self.allocator, "%v{d}", .{value.right}),
                );
            },
            .divide, .remainder => if (left_type.isFloat())
                try self.write("  %v{d} = {s} {s} %v{d}, %v{d}\n", .{
                    value.result,
                    if (value.operator == .divide) "fdiv" else "frem",
                    type_name,
                    value.left,
                    value.right,
                })
            else
                try self.emitDivision(block_id, value, left_type),
            .shift_left, .shift_right => try self.emitShift(block_id, value, left_type),
            .minimum, .maximum => try self.emitFloatMinimumMaximum(value, left_type),
            .bit_and, .bit_xor => try self.write("  %v{d} = {s} {s} %v{d}, %v{d}\n", .{
                value.result,
                if (value.operator == .bit_and) "and" else "xor",
                type_name,
                value.left,
                value.right,
            }),
            .less, .less_equal, .greater, .greater_equal, .equal, .not_equal => {
                if (left_type.isFloat()) {
                    const predicate = switch (value.operator) {
                        .equal => "oeq",
                        .not_equal => "une",
                        .less => "olt",
                        .less_equal => "ole",
                        .greater => "ogt",
                        .greater_equal => "oge",
                        else => unreachable,
                    };
                    return self.write("  %v{d} = fcmp {s} {s} %v{d}, %v{d}\n", .{
                        value.result,
                        predicate,
                        type_name,
                        value.left,
                        value.right,
                    });
                }
                if (!left_type.isInteger() and left_type != .bool) return error.UnsupportedInstruction;
                const predicate = switch (value.operator) {
                    .equal => "eq",
                    .not_equal => "ne",
                    .less => if (left_type.isSignedInteger()) "slt" else "ult",
                    .less_equal => if (left_type.isSignedInteger()) "sle" else "ule",
                    .greater => if (left_type.isSignedInteger()) "sgt" else "ugt",
                    .greater_equal => if (left_type.isSignedInteger()) "sge" else "uge",
                    else => unreachable,
                };
                try self.write("  %v{d} = icmp {s} {s} %v{d}, %v{d}\n", .{
                    value.result,
                    predicate,
                    type_name,
                    value.left,
                    value.right,
                });
            },
        }
    }

    fn emitPlainAggregateEquality(
        self: *FunctionEmitter,
        value: Ir.Instruction.Binary,
        type_value: Ir.Type,
    ) Error!void {
        if (value.operator != .equal and value.operator != .not_equal)
            return error.UnsupportedInstruction;
        var accumulator: ?usize = null;
        const left = try std.fmt.allocPrint(self.allocator, "%v{d}", .{value.left});
        const right = try std.fmt.allocPrint(self.allocator, "%v{d}", .{value.right});
        try self.emitPlainEqualityLeaves(type_value, left, right, &accumulator, 0);
        if (accumulator) |serial| {
            return self.write("  %v{d} = xor i1 %t{d}.aggregate.equal, {s}\n", .{
                value.result,
                serial,
                if (value.operator == .equal) "false" else "true",
            });
        }
        try self.write("  %v{d} = xor i1 false, {s}\n", .{
            value.result,
            if (value.operator == .equal) "true" else "false",
        });
    }

    fn emitPlainEqualityLeaves(
        self: *FunctionEmitter,
        type_value: Ir.Type,
        left: []const u8,
        right: []const u8,
        accumulator: *?usize,
        depth: usize,
    ) Error!void {
        if (type_value.isNumeric() or type_value == .bool) {
            const serial = self.nextTemporary();
            const type_name = try llvmType(self.allocator, self.program, type_value);
            try self.write("  %t{d}.aggregate.leaf = {s} {s} {s}, {s}\n", .{
                serial,
                if (type_value.isFloat()) "fcmp oeq" else "icmp eq",
                type_name,
                left,
                right,
            });
            if (accumulator.*) |previous| {
                try self.write("  %t{d}.aggregate.equal = and i1 %t{d}.aggregate.equal, %t{d}.aggregate.leaf\n", .{
                    serial,
                    previous,
                    serial,
                });
            } else {
                try self.write("  %t{d}.aggregate.equal = xor i1 %t{d}.aggregate.leaf, false\n", .{ serial, serial });
            }
            accumulator.* = serial;
            return;
        }
        const structure_index = type_value.structureIndex() orelse return error.UnsupportedType;
        if (structure_index >= self.program.structures.len or depth >= self.program.structures.len)
            return error.InvalidProgram;
        const structure = self.program.structures[structure_index];
        if (structure.is_class or structure.is_static or structure.is_protocol or structure.collection != null)
            return error.UnsupportedType;
        const type_name = try llvmType(self.allocator, self.program, type_value);
        for (structure.fields, 0..) |field, field_index| {
            const serial = self.nextTemporary();
            try self.write("  %t{d}.aggregate.left = extractvalue {s} {s}, {d}\n", .{
                serial,
                type_name,
                left,
                field_index,
            });
            try self.write("  %t{d}.aggregate.right = extractvalue {s} {s}, {d}\n", .{
                serial,
                type_name,
                right,
                field_index,
            });
            const field_left = try std.fmt.allocPrint(self.allocator, "%t{d}.aggregate.left", .{serial});
            const field_right = try std.fmt.allocPrint(self.allocator, "%t{d}.aggregate.right", .{serial});
            try self.emitPlainEqualityLeaves(field.type, field_left, field_right, accumulator, depth + 1);
        }
    }

    fn emitOptionalEquality(
        self: *FunctionEmitter,
        block_id: usize,
        value: Ir.Instruction.Binary,
        optional_type: Ir.Type,
    ) Error!void {
        if (value.operator != .equal and value.operator != .not_equal)
            return error.UnsupportedInstruction;
        const child = optional_type.optionalChild() orelse return error.InvalidProgram;
        const serial = self.nextTemporary();
        const optional_name = try llvmType(self.allocator, self.program, optional_type);
        if (self.isOptionalNull(value.left) or self.isOptionalNull(value.right)) {
            const operand = if (self.isOptionalNull(value.left)) value.right else value.left;
            try self.write("  %t{d}.present = extractvalue {s} %v{d}, 0\n", .{ serial, optional_name, operand });
            return self.write("  %v{d} = xor i1 %t{d}.present, {s}\n", .{
                value.result,
                serial,
                if (value.operator == .equal) "true" else "false",
            });
        }
        if (child.optionalChild() != null) return error.UnsupportedType;
        const child_name = try llvmType(self.allocator, self.program, child);
        try self.write("  %t{d}.left_present = extractvalue {s} %v{d}, 0\n", .{ serial, optional_name, value.left });
        try self.write("  %t{d}.right_present = extractvalue {s} %v{d}, 0\n", .{ serial, optional_name, value.right });
        try self.write("  %t{d}.same_presence = icmp eq i1 %t{d}.left_present, %t{d}.right_present\n", .{ serial, serial, serial });
        try self.write("  %t{d}.both_present = and i1 %t{d}.left_present, %t{d}.right_present\n", .{ serial, serial, serial });
        try self.write("  %t{d}.left_payload = extractvalue {s} %v{d}, 1\n", .{ serial, optional_name, value.left });
        try self.write("  %t{d}.right_payload = extractvalue {s} %v{d}, 1\n", .{ serial, optional_name, value.right });
        if (child.isFloat()) {
            try self.write("  %t{d}.same_payload = fcmp oeq {s} %t{d}.left_payload, %t{d}.right_payload\n", .{ serial, child_name, serial, serial });
        } else if (child == .str) {
            try self.write("  br i1 %t{d}.both_present, label %b{d}.optional.string.present{d}, label %b{d}.optional.string.absent{d}\n", .{ serial, block_id, serial, block_id, serial });
            try self.write("b{d}.optional.string.present{d}:\n", .{ block_id, serial });
            try self.write("  %t{d}.string_equal = call fastcc i1 @sx_string_equal(ptr %t{d}.left_payload, ptr %t{d}.right_payload)\n", .{ serial, serial, serial });
            try self.write("  br label %b{d}.optional.string.done{d}\n", .{ block_id, serial });
            try self.write("b{d}.optional.string.absent{d}:\n", .{ block_id, serial });
            try self.write("  br label %b{d}.optional.string.done{d}\n", .{ block_id, serial });
            try self.write("b{d}.optional.string.done{d}:\n", .{ block_id, serial });
            try self.write("  %t{d}.same_payload = phi i1 [ %t{d}.string_equal, %b{d}.optional.string.present{d} ], [ false, %b{d}.optional.string.absent{d} ]\n", .{
                serial, serial, block_id, serial, block_id, serial,
            });
        } else if (child.isInteger() or child == .bool or child == .address or classType(self.program, child)) {
            try self.write("  %t{d}.same_payload = icmp eq {s} %t{d}.left_payload, %t{d}.right_payload\n", .{ serial, child_name, serial, serial });
        } else {
            return error.UnsupportedType;
        }
        if (value.operator == .equal) {
            try self.write("  %v{d} = select i1 %t{d}.both_present, i1 %t{d}.same_payload, i1 %t{d}.same_presence\n", .{ value.result, serial, serial, serial });
        } else {
            try self.write("  %t{d}.equal = select i1 %t{d}.both_present, i1 %t{d}.same_payload, i1 %t{d}.same_presence\n", .{ serial, serial, serial, serial });
            try self.write("  %v{d} = xor i1 %t{d}.equal, true\n", .{ value.result, serial });
        }
    }

    fn isOptionalNull(self: *FunctionEmitter, value_id: Ir.ValueId) bool {
        for (self.function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
            .optional_null => |value| if (value.result == value_id) return true,
            else => {},
        };
        return false;
    }

    fn emitFloatMinimumMaximum(
        self: *FunctionEmitter,
        value: Ir.Instruction.Binary,
        type_value: Ir.Type,
    ) Error!void {
        if (!type_value.isFloat()) return error.UnsupportedInstruction;
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, type_value);
        const integer_name = if (type_value == .float32) "i32" else "i64";
        try self.write("  %t{d}.left_nan = fcmp uno {s} %v{d}, %v{d}\n", .{
            serial, type_name, value.left, value.left,
        });
        try self.write("  %t{d}.right_nan = fcmp uno {s} %v{d}, %v{d}\n", .{
            serial, type_name, value.right, value.right,
        });
        try self.write("  %t{d}.ordered = fcmp {s} {s} %v{d}, %v{d}\n", .{
            serial,
            if (value.operator == .minimum) "olt" else "ogt",
            type_name,
            value.left,
            value.right,
        });
        try self.write("  %t{d}.equal = fcmp oeq {s} %v{d}, %v{d}\n", .{
            serial, type_name, value.left, value.right,
        });
        try self.write("  %t{d}.left_bits = bitcast {s} %v{d} to {s}\n", .{
            serial, type_name, value.left, integer_name,
        });
        try self.write("  %t{d}.left_negative = icmp slt {s} %t{d}.left_bits, 0\n", .{
            serial, integer_name, serial,
        });
        try self.write("  %t{d}.equal_value = select i1 %t{d}.left_negative, {s} %v{d}, {s} %v{d}\n", .{
            serial,
            serial,
            type_name,
            if (value.operator == .minimum) value.left else value.right,
            type_name,
            if (value.operator == .minimum) value.right else value.left,
        });
        try self.write("  %t{d}.ordered_value = select i1 %t{d}.ordered, {s} %v{d}, {s} %v{d}\n", .{
            serial, serial, type_name, value.left, type_name, value.right,
        });
        try self.write("  %t{d}.finite_value = select i1 %t{d}.equal, {s} %t{d}.equal_value, {s} %t{d}.ordered_value\n", .{
            serial, serial, type_name, serial, type_name, serial,
        });
        try self.write("  %t{d}.right_checked = select i1 %t{d}.right_nan, {s} %v{d}, {s} %t{d}.finite_value\n", .{
            serial, serial, type_name, value.left, type_name, serial,
        });
        try self.write("  %v{d} = select i1 %t{d}.left_nan, {s} %v{d}, {s} %t{d}.right_checked\n", .{
            value.result, serial, type_name, value.right, type_name, serial,
        });
    }

    fn emitOverflowOperation(
        self: *FunctionEmitter,
        block_id: usize,
        result: Ir.ValueId,
        operation: []const u8,
        type_value: Ir.Type,
        left: []const u8,
        right: []const u8,
    ) Error!void {
        const serial = self.nextTemporary();
        const width = type_value.bitWidth();
        try self.write("  %t{d}.pair = call {{ i{d}, i1 }} @llvm.{s}.with.overflow.i{d}(i{d} {s}, i{d} {s})\n", .{
            serial,
            width,
            operation,
            width,
            width,
            left,
            width,
            right,
        });
        try self.write("  %v{d} = extractvalue {{ i{d}, i1 }} %t{d}.pair, 0\n", .{ result, width, serial });
        try self.write("  %t{d}.overflow = extractvalue {{ i{d}, i1 }} %t{d}.pair, 1\n", .{ serial, width, serial });
        try self.write("  br i1 %t{d}.overflow, label %trap, label %b{d}.cont{d}\n", .{ serial, block_id, serial });
        try self.write("b{d}.cont{d}:\n", .{ block_id, serial });
    }

    fn emitDivision(
        self: *FunctionEmitter,
        block_id: usize,
        value: Ir.Instruction.Binary,
        type_value: Ir.Type,
    ) Error!void {
        if (!type_value.isInteger()) return error.UnsupportedInstruction;
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, type_value);
        try self.write("  %t{d}.zero = icmp eq {s} %v{d}, 0\n", .{ serial, type_name, value.right });
        if (type_value.isSignedInteger()) {
            try self.write("  %t{d}.minimum = icmp eq {s} %v{d}, {d}\n", .{
                serial,
                type_name,
                value.left,
                integerMinimum(type_value),
            });
            try self.write("  %t{d}.minusone = icmp eq {s} %v{d}, -1\n", .{ serial, type_name, value.right });
            try self.write("  %t{d}.overflow = and i1 %t{d}.minimum, %t{d}.minusone\n", .{ serial, serial, serial });
            try self.write("  %t{d}.invalid = or i1 %t{d}.zero, %t{d}.overflow\n", .{ serial, serial, serial });
        } else {
            try self.write("  %t{d}.invalid = xor i1 %t{d}.zero, false\n", .{ serial, serial });
        }
        try self.write("  br i1 %t{d}.invalid, label %trap, label %b{d}.cont{d}\n", .{ serial, block_id, serial });
        try self.write("b{d}.cont{d}:\n", .{ block_id, serial });
        const operation = if (type_value.isSignedInteger())
            (if (value.operator == .divide) "sdiv" else "srem")
        else if (value.operator == .divide) "udiv" else "urem";
        try self.write("  %v{d} = {s} {s} %v{d}, %v{d}\n", .{
            value.result,
            operation,
            type_name,
            value.left,
            value.right,
        });
    }

    fn emitShift(
        self: *FunctionEmitter,
        block_id: usize,
        value: Ir.Instruction.Binary,
        left_type: Ir.Type,
    ) Error!void {
        if (!left_type.isInteger()) return error.UnsupportedInstruction;
        const right_type = try self.valueType(value.right);
        if (!right_type.isInteger()) return error.UnsupportedInstruction;
        if (try self.valueType(value.result) != left_type) return error.InvalidProgram;
        const serial = self.nextTemporary();
        const right_name = try llvmType(self.allocator, self.program, right_type);
        if (right_type.isSignedInteger()) {
            try self.write("  %t{d}.negative = icmp slt {s} %v{d}, 0\n", .{ serial, right_name, value.right });
        } else {
            try self.write("  %t{d}.negative = xor i1 false, false\n", .{serial});
        }
        try self.write("  %t{d}.large = icmp uge {s} %v{d}, {d}\n", .{
            serial,
            right_name,
            value.right,
            left_type.bitWidth(),
        });
        try self.write("  %t{d}.invalid = or i1 %t{d}.negative, %t{d}.large\n", .{ serial, serial, serial });
        try self.write("  br i1 %t{d}.invalid, label %trap, label %b{d}.cont{d}\n", .{ serial, block_id, serial });
        try self.write("b{d}.cont{d}:\n", .{ block_id, serial });
        const left_name = try llvmType(self.allocator, self.program, left_type);
        if (right_type.bitWidth() < left_type.bitWidth()) {
            try self.write("  %t{d}.count = zext {s} %v{d} to {s}\n", .{ serial, right_name, value.right, left_name });
        } else if (right_type.bitWidth() > left_type.bitWidth()) {
            try self.write("  %t{d}.count = trunc {s} %v{d} to {s}\n", .{ serial, right_name, value.right, left_name });
        } else {
            try self.write("  %t{d}.count = select i1 true, {s} %v{d}, {s} %v{d}\n", .{
                serial,
                left_name,
                value.right,
                left_name,
                value.right,
            });
        }
        try self.write("  %v{d} = {s} {s} %v{d}, %t{d}.count\n", .{
            value.result,
            if (value.operator == .shift_left) "shl" else "lshr",
            left_name,
            value.left,
            serial,
        });
    }

    fn emitConvert(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Convert) Error!void {
        if (value.source == value.target) return self.copyValue(value.result, value.operand);
        if (value.source == .float32 and value.target == .float64)
            return self.write("  %v{d} = fpext float %v{d} to double\n", .{ value.result, value.operand });
        if (value.source == .float64 and value.target == .float32)
            return self.emitFloatNarrowing(block_id, value);
        if (value.source.isInteger() and value.target.isFloat())
            return self.emitIntegerToFloat(block_id, value);
        if (value.source.isFloat() and value.target.isInteger())
            return self.emitFloatToInteger(block_id, value);
        if (!value.source.isInteger() or !value.target.isInteger()) {
            std.debug.print(
                "silex LLVM evaluation: unsupported conversion {s} -> {s}, checked {}, at {d}:{d}:{d}\n",
                .{
                    try reportTypeName(self.allocator, self.program, value.source),
                    try reportTypeName(self.allocator, self.program, value.target),
                    value.checked,
                    value.position.file,
                    value.position.line,
                    value.position.column,
                },
            );
            return error.UnsupportedInstruction;
        }
        const serial = self.nextTemporary();
        const source_name = try llvmType(self.allocator, self.program, value.source);
        try self.write("  %t{d}.wide = {s} {s} %v{d} to i128\n", .{
            serial,
            if (value.source.isSignedInteger()) "sext" else "zext",
            source_name,
            value.operand,
        });
        try self.write("  %t{d}.low = icmp slt i128 %t{d}.wide, {d}\n", .{
            serial,
            serial,
            integerMinimum(value.target),
        });
        try self.write("  %t{d}.high = icmp sgt i128 %t{d}.wide, {d}\n", .{
            serial,
            serial,
            integerMaximum(value.target),
        });
        try self.write("  %t{d}.invalid = or i1 %t{d}.low, %t{d}.high\n", .{ serial, serial, serial });
        try self.emitConversionFailure(block_id, serial, value, false);
        try self.write("  %v{d} = trunc i128 %t{d}.wide to {s}\n", .{
            value.result,
            serial,
            try llvmType(self.allocator, self.program, value.target),
        });
    }

    fn emitIntegerToFloat(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Convert) Error!void {
        const source_name = try llvmType(self.allocator, self.program, value.source);
        const target_name = try llvmType(self.allocator, self.program, value.target);
        const signed = value.source.isSignedInteger();
        try self.write("  %v{d} = {s} {s} %v{d} to {s}\n", .{
            value.result,
            if (signed) "sitofp" else "uitofp",
            source_name,
            value.operand,
            target_name,
        });
        if (!value.checked) return;

        const serial = self.nextTemporary();
        const width = value.source.bitWidth();
        const floating_suffix = if (value.target == .float32) "f32" else "f64";
        try self.write("  %t{d}.roundtrip = call {s} @llvm.{s}.sat.i{d}.{s}({s} %v{d})\n", .{
            serial,
            source_name,
            if (signed) "fptosi" else "fptoui",
            width,
            floating_suffix,
            target_name,
            value.result,
        });
        try self.write("  %t{d}.same = icmp eq {s} %t{d}.roundtrip, %v{d}\n", .{
            serial,
            source_name,
            serial,
            value.operand,
        });
        const precision: u7 = if (value.target == .float32) 24 else 53;
        const maximum_is_inexact = if (signed) width - 1 > precision else width > precision;
        if (maximum_is_inexact) {
            try self.write("  %t{d}.maximum = icmp eq {s} %v{d}, {d}\n", .{
                serial,
                source_name,
                value.operand,
                integerMaximum(value.source),
            });
            try self.write("  %t{d}.not_maximum = xor i1 %t{d}.maximum, true\n", .{ serial, serial });
            try self.write("  %t{d}.exact = and i1 %t{d}.same, %t{d}.not_maximum\n", .{ serial, serial, serial });
        } else {
            try self.write("  %t{d}.exact = xor i1 %t{d}.same, false\n", .{ serial, serial });
        }
        try self.emitConversionFailure(block_id, serial, value, true);
    }

    fn emitFloatNarrowing(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Convert) Error!void {
        try self.write("  %v{d} = fptrunc double %v{d} to float\n", .{ value.result, value.operand });
        if (!value.checked) return;
        const serial = self.nextTemporary();
        try self.write("  %t{d}.roundtrip = fpext float %v{d} to double\n", .{ serial, value.result });
        try self.write("  %t{d}.exact = fcmp oeq double %v{d}, %t{d}.roundtrip\n", .{ serial, value.operand, serial });
        try self.emitConversionFailure(block_id, serial, value, true);
    }

    fn emitFloatToInteger(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.Convert) Error!void {
        const serial = self.nextTemporary();
        const source_name = try llvmType(self.allocator, self.program, value.source);
        const target_name = try llvmType(self.allocator, self.program, value.target);
        const width = value.target.bitWidth();
        const signed = value.target.isSignedInteger();
        const lower = integerMinimum(value.target);
        const upper_exclusive = @as(i128, integerMaximum(value.target)) + 1;

        try self.write("  %t{d}.lower = {s} i128 {d} to {s}\n", .{
            serial,
            if (signed) "sitofp" else "uitofp",
            lower,
            source_name,
        });
        try self.write("  %t{d}.upper = {s} i128 {d} to {s}\n", .{
            serial,
            if (signed) "sitofp" else "uitofp",
            upper_exclusive,
            source_name,
        });
        try self.write("  %t{d}.low = fcmp olt {s} %v{d}, %t{d}.lower\n", .{ serial, source_name, value.operand, serial });
        try self.write("  %t{d}.high = fcmp oge {s} %v{d}, %t{d}.upper\n", .{ serial, source_name, value.operand, serial });
        try self.write("  %t{d}.outside = or i1 %t{d}.low, %t{d}.high\n", .{ serial, serial, serial });
        try self.write("  %t{d}.converted = call {s} @llvm.{s}.sat.i{d}.{s}({s} %v{d})\n", .{
            serial,
            target_name,
            if (signed) "fptosi" else "fptoui",
            width,
            if (value.source == .float32) "f32" else "f64",
            source_name,
            value.operand,
        });
        try self.write("  %t{d}.roundtrip = {s} {s} %t{d}.converted to {s}\n", .{
            serial,
            if (signed) "sitofp" else "uitofp",
            target_name,
            serial,
            source_name,
        });
        try self.write("  %t{d}.integral = fcmp oeq {s} %v{d}, %t{d}.roundtrip\n", .{ serial, source_name, value.operand, serial });
        try self.write("  %t{d}.not_integral = xor i1 %t{d}.integral, true\n", .{ serial, serial });
        try self.write("  %t{d}.invalid = or i1 %t{d}.outside, %t{d}.not_integral\n", .{ serial, serial, serial });
        try self.emitConversionFailure(block_id, serial, value, false);
        try self.write("  %v{d} = add {s} %t{d}.converted, 0\n", .{ value.result, target_name, serial });
    }

    fn emitCall(self: *FunctionEmitter, value: Ir.Instruction.Call) Error!void {
        if (value.function >= self.program.functions.len) return error.InvalidProgram;
        const callee = self.program.functions[value.function];
        if (callee.capture_types.len != 0 or callee.parameter_types.len != value.arguments.len)
            return error.InvalidProgram;
        try self.output.appendSlice(self.allocator, "  ");
        if (value.result) |result| try self.write("%v{d} = ", .{result});
        try self.write("call fastcc {s} @sx_{d}(ptr null", .{ try llvmType(self.allocator, self.program, callee.return_type), value.function });
        for (value.arguments, 0..) |argument, index| {
            try self.write(", {s} %v{d}", .{ try llvmType(self.allocator, self.program, callee.parameter_types[index]), argument });
        }
        try self.output.appendSlice(self.allocator, ")\n");
    }

    fn emitIndirectCall(self: *FunctionEmitter, value: Ir.Instruction.IndirectCall) Error!void {
        const signature_index = (try self.valueType(value.callee)).functionIndex() orelse
            return error.InvalidProgram;
        if (signature_index >= self.program.function_types.len) return error.InvalidProgram;
        const signature = self.program.function_types[signature_index];
        if (signature.parameter_types.len != value.arguments.len) return error.InvalidProgram;
        if (signature.return_type == .void) {
            if (value.result != null) return error.InvalidProgram;
        } else {
            const result = value.result orelse return error.InvalidProgram;
            if (try self.valueType(result) != signature.return_type) return error.InvalidProgram;
        }
        const serial = self.nextTemporary();
        try self.write("  %t{d}.closure.code = extractvalue {{ ptr, ptr, ptr }} %v{d}, 0\n", .{ serial, value.callee });
        try self.write("  %t{d}.closure.environment = extractvalue {{ ptr, ptr, ptr }} %v{d}, 1\n", .{ serial, value.callee });
        try self.output.appendSlice(self.allocator, "  ");
        if (value.result) |result| try self.write("%v{d} = ", .{result});
        try self.write("call fastcc {s} %t{d}.closure.code(ptr %t{d}.closure.environment", .{
            try llvmType(self.allocator, self.program, signature.return_type),
            serial,
            serial,
        });
        for (value.arguments, signature.parameter_types, 0..) |argument, parameter_type, index| {
            if (try self.valueType(argument) != parameter_type) return error.InvalidProgram;
            _ = index;
            try self.write(", {s} %v{d}", .{
                try llvmType(self.allocator, self.program, parameter_type),
                argument,
            });
        }
        try self.output.appendSlice(self.allocator, ")\n");
    }

    fn emitBoundaryCall(self: *FunctionEmitter, value: Ir.Instruction.BoundaryCall) Error!void {
        if (value.function >= self.boundaries.len) return error.InvalidProgram;
        const boundary = self.boundaries[value.function];
        if (!supportsDirectBoundary(boundary)) return error.UnsupportedType;
        if (boundary.parameters.len != value.arguments.len) return error.InvalidProgram;
        try self.output.appendSlice(self.allocator, "  ");
        if (boundary.return_type == .void) {
            if (value.result != null) return error.InvalidProgram;
        } else {
            const result = value.result orelse return error.InvalidProgram;
            if (try self.valueType(result) != boundary.return_type) return error.InvalidProgram;
            try self.write("%v{d} = ", .{result});
        }
        try self.write("call {s} @{s}(", .{
            try llvmType(self.allocator, self.program, boundary.return_type),
            boundary.source_name,
        });
        for (value.arguments, 0..) |argument, index| {
            if (try self.valueType(argument) != boundary.parameters[index]) return error.InvalidProgram;
            if (index != 0) try self.output.appendSlice(self.allocator, ", ");
            try self.write("{s} %v{d}", .{
                try llvmType(self.allocator, self.program, boundary.parameters[index]),
                argument,
            });
        }
        try self.output.appendSlice(self.allocator, ")\n");
    }

    fn emitPrint(self: *FunctionEmitter, value: Ir.Instruction.Print) Error!void {
        const type_value = try self.valueType(value.value);
        const serial = self.nextTemporary();
        if (type_value == .str) {
            try self.write("  %t{d}.tagged = load i64, ptr %v{d}\n", .{ serial, value.value });
            try self.write("  %t{d}.length = and i64 %t{d}.tagged, 9223372036854775807\n", .{ serial, serial });
            try self.write("  %t{d}.data = getelementptr i8, ptr %v{d}, i64 8\n", .{ serial, value.value });
            try self.write("  %t{d}.print = call i64 @write(i32 1, ptr %t{d}.data, i64 %t{d}.length)\n", .{ serial, serial, serial });
            if (value.newline) try self.write("  %t{d}.newline = call i64 @write(i32 1, ptr @.newline, i64 1)\n", .{serial});
            return;
        }
        if (type_value == .bool) {
            try self.write("  %t{d}.text = select i1 %v{d}, ptr @.true, ptr @.false\n", .{ serial, value.value });
            try self.write("  %t{d}.print = call i32 (i32, ptr, ...) @dprintf(i32 1, ptr @{s}, ptr %t{d}.text)\n", .{
                serial,
                if (value.newline) ".fmt.boolean" else ".fmt.boolean.inline",
                serial,
            });
            return;
        }
        if (!type_value.isInteger()) return error.UnsupportedType;
        const type_name = try llvmType(self.allocator, self.program, type_value);
        if (type_value.bitWidth() < 64) {
            try self.write("  %t{d}.wide = {s} {s} %v{d} to i64\n", .{
                serial,
                if (type_value.isSignedInteger()) "sext" else "zext",
                type_name,
                value.value,
            });
        } else {
            try self.write("  %t{d}.wide = select i1 true, i64 %v{d}, i64 %v{d}\n", .{
                serial,
                value.value,
                value.value,
            });
        }
        const format = if (type_value.isSignedInteger())
            (if (value.newline) ".fmt.signed" else ".fmt.signed.inline")
        else if (value.newline) ".fmt.unsigned" else ".fmt.unsigned.inline";
        try self.write("  %t{d}.print = call i32 (i32, ptr, ...) @dprintf(i32 1, ptr @{s}, i64 %t{d}.wide)\n", .{
            serial,
            format,
            serial,
        });
    }

    fn emitTerminator(self: *FunctionEmitter, terminator: Ir.Terminator) Error!void {
        switch (terminator) {
            .jump => |target| try self.write("  br label %b{d}\n", .{target}),
            .branch => |branch| try self.write("  br i1 %v{d}, label %b{d}, label %b{d}\n", .{
                branch.condition,
                branch.then_block,
                branch.else_block,
            }),
            .return_value => |value| try self.write("  ret {s} %v{d}\n", .{
                try llvmType(self.allocator, self.program, self.function.return_type),
                value,
            }),
            .return_void => try self.output.appendSlice(self.allocator, "  ret void\n"),
            .panic => |value| {
                if (try self.valueType(value.message) != .str or value.position.file >= self.program.files.len)
                    return error.InvalidProgram;
                try self.write("  call fastcc void @sx_panic(ptr @sx.file.{d}, i64 {d}, i64 {d}, ptr %v{d})\n", .{
                    value.position.file,
                    value.position.line,
                    value.position.column,
                    value.message,
                });
                try self.output.appendSlice(self.allocator, "  unreachable\n");
            },
        }
    }

    fn valueType(self: *FunctionEmitter, value: Ir.ValueId) Error!Ir.Type {
        if (value >= self.function.value_types.len) return error.InvalidProgram;
        return self.function.value_types[value];
    }

    fn nextTemporary(self: *FunctionEmitter) usize {
        const temporary = self.temporary;
        self.temporary += 1;
        return temporary;
    }

    fn write(self: *FunctionEmitter, comptime format: []const u8, arguments: anytype) Error!void {
        return appendFmt(self.output, self.allocator, format, arguments);
    }
};

fn emitBoundaryDeclarations(
    output: *std.ArrayList(u8),
    allocator: Allocator,
    program: Ir.Program,
    boundaries: []const Silex.Boundary.Function,
    direct_sites_by_function: []const usize,
) Error!void {
    if (direct_sites_by_function.len != boundaries.len) return error.InvalidProgram;
    var emitted = false;
    boundary: for (boundaries, 0..) |function, index| {
        if (direct_sites_by_function[index] == 0) continue;
        if (!supportsDirectBoundary(function)) return error.UnsupportedType;
        for (boundaries[0..index], direct_sites_by_function[0..index]) |previous, previous_sites| {
            if (previous_sites == 0 or !std.mem.eql(u8, previous.source_name, function.source_name)) continue;
            if (!std.mem.eql(u8, previous.provider, function.provider) or
                previous.return_type != function.return_type or
                !std.mem.eql(Ir.Type, previous.parameters, function.parameters))
            {
                std.debug.print(
                    "silex LLVM evaluation: boundary symbol '{s}' has conflicting providers or signatures\n",
                    .{function.source_name},
                );
                return error.InvalidProgram;
            }
            continue :boundary;
        }
        try appendFmt(output, allocator, "declare {s} @{s}(", .{
            try llvmType(allocator, program, function.return_type),
            function.source_name,
        });
        for (function.parameters, 0..) |parameter, parameter_index| {
            if (parameter_index != 0) try output.appendSlice(allocator, ", ");
            try output.appendSlice(allocator, try llvmType(allocator, program, parameter));
        }
        try output.appendSlice(allocator, ")\n");
        emitted = true;
    }
    if (emitted) try output.append(allocator, '\n');
}

fn supportsDirectBoundary(function: Silex.Boundary.Function) bool {
    if (!supportsBoundaryType(function.return_type)) return false;
    for (function.parameters) |parameter| if (!supportsBoundaryType(parameter)) return false;
    return true;
}

fn supportsBoundaryType(type_value: Ir.Type) bool {
    return switch (type_value) {
        .void,
        .bool,
        .int8,
        .uint8,
        .int16,
        .uint16,
        .int32,
        .uint32,
        .int,
        .uint,
        .float32,
        .float64,
        .address,
        => true,
        else => false,
    };
}

