// Experimental backend forked from the audited optimizer emitter; oracle guards stay unchanged.
const std = @import("std");
const Silex = @import("silex_optimizer_api");
const Coverage = @import("../OptimizerOracle/LlvmCoverage.zig");
const IrStats = @import("../OptimizerOracle/IrStats.zig");

const Allocator = std.mem.Allocator;
const Ir = Silex.Ir;

pub const Error = Allocator.Error || error{
    InvalidProgram,
    UnsupportedInstruction,
    UnsupportedType,
};

pub fn emit(allocator: Allocator, program: Ir.Program) Error![]u8 {
    return emitWithBoundaries(allocator, program, &.{});
}

pub fn emitWithBoundaries(
    allocator: Allocator,
    program: Ir.Program,
    boundaries: []const Silex.Boundary.Function,
) Error![]u8 {
    const reachable = try IrStats.reachableFunctions(allocator, program);
    defer allocator.free(reachable);
    const boundary_use = try inspectBoundaryUse(allocator, program, boundaries, reachable);
    defer allocator.free(boundary_use.direct_sites_by_function);
    if (boundary_use.unsupported != 0 or boundary_use.indirect_sites != 0) {
        const first = boundary_use.first_unsupported;
        std.debug.print(
            "silex LLVM evaluation: emitter rejected {d} reachable package boundary functions across {d} direct and {d} indirect call sites",
            .{ boundary_use.unsupported, boundary_use.direct_sites, boundary_use.indirect_sites },
        );
        if (first) |index| std.debug.print(
            "; first unsupported reachable boundary is '{s}' from '{s}'",
            .{ boundaries[index].source_name, boundaries[index].provider },
        );
        std.debug.print("\n", .{});
        return error.UnsupportedInstruction;
    }
    const global_use = try inspectGlobalUse(allocator, program, reachable);
    defer allocator.free(global_use.loads);
    defer allocator.free(global_use.stores);
    var unsupported_globals: usize = 0;
    var first_unsupported_global: ?usize = null;
    for (program.globals, 0..) |global, index| {
        if (global_use.loads[index] == 0 and global_use.stores[index] == 0) continue;
        if (global_use.stores[index] != 0 and !global.mutable) return error.InvalidProgram;
        if (supportsStaticGlobal(program, global)) continue;
        unsupported_globals += 1;
        if (first_unsupported_global == null) first_unsupported_global = index;
    }
    if (unsupported_globals != 0) {
        std.debug.print(
            "silex LLVM evaluation: emitter rejected {d} of {d} reachable global values across {d} loads and {d} stores; first unsupported reachable global is '{s}'\n",
            .{
                unsupported_globals,
                global_use.used,
                global_use.load_sites,
                global_use.store_sites,
                program.globals[first_unsupported_global.?].name,
            },
        );
        return error.UnsupportedInstruction;
    }
    var output: std.ArrayList(u8) = .empty;
    try output.appendSlice(allocator,
        \\; Generated by the explicit Silex LLVM evaluation backend. Experimental.
        \\target datalayout = "e-m:o-p270:32:32-p271:32:32-p272:64:64-i64:64-i128:128-n32:64-S128-Fn32"
        \\target triple = "arm64-apple-macosx26.0.0"
        \\
        \\@.fmt.signed = private constant [6 x i8] c"%lld\0A\00"
        \\@.fmt.signed.inline = private constant [5 x i8] c"%lld\00"
        \\@.fmt.unsigned = private constant [6 x i8] c"%llu\0A\00"
        \\@.fmt.unsigned.inline = private constant [5 x i8] c"%llu\00"
        \\@.fmt.boolean = private constant [4 x i8] c"%s\0A\00"
        \\@.fmt.boolean.inline = private constant [3 x i8] c"%s\00"
        \\@.true = private constant [5 x i8] c"true\00"
        \\@.false = private constant [6 x i8] c"false\00"
        \\@sx.format.true = private constant { i64, [4 x i8] } { i64 4, [4 x i8] c"true" }
        \\@sx.format.false = private constant { i64, [5 x i8] } { i64 5, [5 x i8] c"false" }
        \\@.newline = private constant [1 x i8] c"\0A"
        \\
        \\declare i32 @dprintf(i32, ptr, ...)
        \\declare i64 @write(i32, ptr, i64)
        \\declare ptr @malloc(i64)
        \\declare i64 @silex_format_signed(i64, ptr)
        \\declare i64 @silex_format_unsigned(i64, ptr)
        \\declare i64 @silex_format_float(i64, ptr, i64)
        \\declare void @llvm.memcpy.p0.p0.i64(ptr, ptr, i64, i1 immarg)
        \\declare void @exit(i32) noreturn
        \\
    );
    try output.appendSlice(allocator, @import("Runtime.zig").text);
    if (reachableUsesMutex(program, reachable)) try output.appendSlice(allocator,
        \\@sx.mutex = private global [8 x i64] zeroinitializer, align 8
        \\declare void @os_unfair_recursive_lock_lock_with_options(ptr, i64)
        \\declare void @os_unfair_recursive_lock_unlock(ptr)
        \\
    );
    try emitSourceFiles(&output, allocator, program);
    for ([_]u7{ 8, 16, 32, 64 }) |width| {
        for ([_][]const u8{ "sadd", "ssub", "smul", "uadd", "usub", "umul" }) |operation| {
            try appendFmt(
                &output,
                allocator,
                "declare {{ i{d}, i1 }} @llvm.{s}.with.overflow.i{d}(i{d}, i{d})\n",
                .{ width, operation, width, width, width },
            );
        }
        for ([_]struct { suffix: []const u8, type_name: []const u8 }{
            .{ .suffix = "f32", .type_name = "float" },
            .{ .suffix = "f64", .type_name = "double" },
        }) |floating| {
            try appendFmt(
                &output,
                allocator,
                "declare i{d} @llvm.fptosi.sat.i{d}.{s}({s})\n",
                .{ width, width, floating.suffix, floating.type_name },
            );
            try appendFmt(
                &output,
                allocator,
                "declare i{d} @llvm.fptoui.sat.i{d}.{s}({s})\n",
                .{ width, width, floating.suffix, floating.type_name },
            );
        }
    }
    try output.append(allocator, '\n');
    try emitBoundaryDeclarations(
        &output,
        allocator,
        program,
        boundaries,
        boundary_use.direct_sites_by_function,
    );
    try emitGlobalDeclarations(&output, allocator, program, global_use);
    var main_function: ?usize = null;
    const lowered_functions = try allocator.alloc(?Ir.Function, program.functions.len);
    defer allocator.free(lowered_functions);
    @memset(lowered_functions, null);
    for (program.functions, 0..) |function, function_id| {
        if (std.mem.eql(u8, function.name, "main")) {
            if (main_function != null) return error.InvalidProgram;
            main_function = function_id;
        }
        if (!reachable[function_id]) continue;
        lowered_functions[function_id] = try @import("../OptimizerOracle/LlvmValues.zig").lower(allocator, function);
    }
    try emitStringLiterals(&output, allocator, program, lowered_functions);
    // Normalize the whole reachable value graph before declaring aggregate
    // layouts. Unsupported instructions therefore keep their precise
    // attribution even when the composed program also contains types outside
    // the prototype.
    for (program.structures, 0..) |structure, structure_index| {
        if (enumIndexForStructure(program, structure_index)) |enumeration_index| {
            if (plainTagEnum(program, enumeration_index)) continue;
            if (try rawEnumType(program, enumeration_index)) |raw_type| {
                try appendFmt(
                    &output,
                    allocator,
                    "%sx.enum.{d} = type {{ i64, {s} }}\n",
                    .{ enumeration_index, try llvmType(allocator, program, raw_type) },
                );
                continue;
            }
            const payload_slots = enumPayloadStorageSlots(program, enumeration_index, 0) catch |err| switch (err) {
                error.UnsupportedType => continue,
                else => return err,
            };
            try appendFmt(
                &output,
                allocator,
                "%sx.enum.{d} = type {{ i64, [{d} x i64] }}\n",
                .{ enumeration_index, payload_slots },
            );
            continue;
        }
        if (structure.collection) |collection| {
            if (collection.length) |length| {
                try appendFmt(&output, allocator, "%sx.type.{d} = type [{d} x {s}]\n", .{
                    structure_index,
                    length,
                    try llvmType(allocator, program, collection.element),
                });
            } else {
                try appendFmt(&output, allocator, "%sx.type.{d} = type {{ ptr, i64 }}\n", .{structure_index});
            }
            continue;
        }
        // Class values remain pointers, while their allocation follows the
        // native four-slot header and fixed-width leaf storage ABI.
        if (structure.is_class) {
            if (!materialClassStorage(program, structure_index)) continue;
            try appendFmt(&output, allocator, "%sx.class.{d} = type {{ i64, i64, i64, i64, [{d} x i64] }}\n", .{
                structure_index,
                try classStorageSlots(program, structure_index),
            });
            continue;
        }
        if (structure.is_protocol) {
            const payload_slots = protocolPayloadStorageSlots(program, structure_index, 0) catch |err| {
                std.debug.print("silex LLVM evaluation: cannot declare protocol type '{s}': {t}\n", .{ structure.name, err });
                return err;
            };
            try appendFmt(
                &output,
                allocator,
                "%sx.protocol.{d} = type {{ i64, [{d} x i64] }}\n",
                .{ structure_index, payload_slots },
            );
            continue;
        }
        // Static structures are namespaces, not runtime values. llvmType
        // still rejects any attempt to use one in a material value position.
        if (structure.is_static) continue;
        try appendFmt(&output, allocator, "%sx.type.{d} = type {{ ", .{structure_index});
        for (structure.fields, 0..) |field, field_index| {
            if (field_index != 0) try output.appendSlice(allocator, ", ");
            const field_type = llvmType(allocator, program, field.type) catch |err| {
                std.debug.print("silex LLVM evaluation: cannot declare structure '{s}' field '{s}': {t}\n", .{ structure.name, field.name, err });
                return err;
            };
            try output.appendSlice(allocator, field_type);
        }
        try output.appendSlice(allocator, " }\n");
    }
    if (program.structures.len != 0) try output.append(allocator, '\n');

    for (program.functions, 0..) |function, function_id| {
        if (!reachable[function_id]) continue;
        var emitter: FunctionEmitter = .{
            .allocator = allocator,
            .output = &output,
            .program = program,
            .boundaries = boundaries,
            .function = lowered_functions[function_id].?,
            .function_id = function_id,
        };
        emitter.emit() catch |err| {
            std.debug.print(
                "silex LLVM evaluation: emitter rejected function '{s}': {t}\n",
                .{ function.name, err },
            );
            return err;
        };
    }
    const callback_targets = try inspectCallbackTargets(allocator, program, lowered_functions, reachable);
    defer allocator.free(callback_targets);
    try emitCallbackWrappers(&output, allocator, program, callback_targets);
    const main_id = main_function orelse return error.InvalidProgram;
    const main = program.functions[main_id];
    if (main.parameter_types.len != 0 or main.return_type != .void) return error.UnsupportedType;
    try appendFmt(&output, allocator,
        \\define i32 @main() {{
        \\entry:
        \\  call fastcc void @sx_{d}(ptr null)
        \\  call fastcc void @sx_finish()
        \\  ret i32 0
        \\}}
        \\
    , .{main_id});
    return output.toOwnedSlice(allocator);
}

fn inspectCallbackTargets(
    allocator: Allocator,
    program: Ir.Program,
    functions: []const ?Ir.Function,
    reachable: []const bool,
) Error![]bool {
    const targets = try allocator.alloc(bool, program.functions.len);
    @memset(targets, false);
    for (functions, reachable) |optional_function, is_reachable| {
        if (!is_reachable) continue;
        const function = optional_function orelse return error.InvalidProgram;
        for (function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
            .copy => |copy| {
                if (copy.result >= function.value_types.len or copy.operand >= function.value_types.len)
                    return error.InvalidProgram;
                if (function.value_types[copy.result] != .uint or
                    function.value_types[copy.operand].functionIndex() == null) continue;
                const target = directFunctionReference(function, copy.operand) orelse
                    return error.UnsupportedInstruction;
                if (target >= program.functions.len or program.functions[target].capture_types.len != 0)
                    return error.UnsupportedInstruction;
                targets[target] = true;
            },
            else => {},
        };
    }
    return targets;
}

fn directFunctionReference(function: Ir.Function, value: Ir.ValueId) ?Ir.FunctionId {
    var target: ?Ir.FunctionId = null;
    for (function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
        .function_reference => |reference| if (reference.result == value) {
            if (target != null and target.? != reference.function) return null;
            target = reference.function;
        },
        else => {},
    };
    return target;
}

fn emitCallbackWrappers(
    output: *std.ArrayList(u8),
    allocator: Allocator,
    program: Ir.Program,
    targets: []const bool,
) Error!void {
    for (targets, 0..) |selected, function_id| {
        if (!selected) continue;
        const function = program.functions[function_id];
        if (function.capture_types.len != 0) return error.UnsupportedInstruction;
        const return_name = try llvmType(allocator, program, function.return_type);
        try appendFmt(output, allocator, "define internal {s} @sx.c.callback.{d}(", .{ return_name, function_id });
        for (function.parameter_types, 0..) |parameter, index| {
            if (index != 0) try output.appendSlice(allocator, ", ");
            try appendFmt(output, allocator, "{s} %v{d}", .{ try llvmType(allocator, program, parameter), index });
        }
        try output.appendSlice(allocator, ") {\nentry:\n  ");
        if (function.return_type != .void) try output.appendSlice(allocator, "%result = ");
        try appendFmt(output, allocator, "call fastcc {s} @sx_{d}(ptr null", .{ return_name, function_id });
        for (function.parameter_types, 0..) |parameter, index| try appendFmt(
            output,
            allocator,
            ", {s} %v{d}",
            .{ try llvmType(allocator, program, parameter), index },
        );
        try output.appendSlice(allocator, ")\n  ret ");
        if (function.return_type == .void)
            try output.appendSlice(allocator, "void\n}\n")
        else
            try appendFmt(output, allocator, "{s} %result\n}}\n", .{return_name});
    }
}

pub fn closureReport(
    allocator: Allocator,
    program: Ir.Program,
    boundaries: []const Silex.Boundary.Function,
) Error![]u8 {
    const reachable = try IrStats.reachableFunctions(allocator, program);
    defer allocator.free(reachable);
    const boundary_use = try inspectBoundaryUse(allocator, program, boundaries, reachable);
    defer allocator.free(boundary_use.direct_sites_by_function);
    const global_use = try inspectGlobalUse(allocator, program, reachable);
    defer allocator.free(global_use.loads);
    defer allocator.free(global_use.stores);
    const instruction_use = inspectInstructionUse(program, reachable);
    const instruction_coverage = try instructionCoverageEntries(allocator, instruction_use);
    defer allocator.free(instruction_coverage);

    var reachable_function_count: usize = 0;
    for (reachable) |is_reachable| if (is_reachable) {
        reachable_function_count += 1;
    };
    var direct_function_count: usize = 0;
    for (boundary_use.direct_sites_by_function) |sites| if (sites != 0) {
        direct_function_count += 1;
    };
    const entries = try allocator.alloc(BoundaryInventoryEntry, direct_function_count);
    var entry_index: usize = 0;
    for (boundaries, 0..) |boundary, index| {
        const sites = boundary_use.direct_sites_by_function[index];
        if (sites == 0) continue;
        entries[entry_index] = .{
            .index = index,
            .owner = boundary.owner,
            .name = boundary.name,
            .provider = boundary.provider,
            .source_name = boundary.source_name,
            .parameters = boundary.parameters,
            .return_type = boundary.return_type,
            .direct_sites = sites,
            .supported_by_prototype = supportsDirectBoundary(boundary),
        };
        entry_index += 1;
    }
    const globals = try allocator.alloc(GlobalInventoryEntry, global_use.used);
    var global_entry_index: usize = 0;
    for (program.globals, 0..) |global, index| {
        if (global_use.loads[index] == 0 and global_use.stores[index] == 0) continue;
        globals[global_entry_index] = .{
            .index = index,
            .name = global.name,
            .type = global.type,
            .type_name = try reportTypeName(allocator, program, global.type),
            .mutable = global.mutable,
            .runtime_initialized = global.runtime_initialized,
            .bits = global.bits,
            .extra_bits = global.extra_bits,
            .loads = global_use.loads[index],
            .stores = global_use.stores[index],
        };
        global_entry_index += 1;
    }
    return std.json.Stringify.valueAlloc(allocator, .{
        .boundary_table_size = boundaries.len,
        .reachable_functions = reachable_function_count,
        .reachable_direct_boundary_functions = direct_function_count,
        .direct_call_sites = boundary_use.direct_sites,
        .indirect_call_sites = boundary_use.indirect_sites,
        .functions = entries,
        .global_table_size = program.globals.len,
        .reachable_global_values = global_use.used,
        .global_load_sites = global_use.load_sites,
        .global_store_sites = global_use.store_sites,
        .globals = globals,
        .instruction_sites = instruction_use.sites_total,
        .conditionally_supported_instruction_sites = instruction_use.conditional_sites,
        .abstract_lifetime_instruction_sites = instruction_use.abstract_lifetime_sites,
        .unsupported_instruction_sites = instruction_use.unsupported_sites,
        .unsupported_instruction_kinds = instruction_use.unsupported_kinds,
        .functions_with_unsupported_instructions = instruction_use.functions_with_unsupported,
        .instruction_coverage = instruction_coverage,
    }, .{ .whitespace = .indent_2 });
}

const BoundaryInventoryEntry = struct {
    index: usize,
    owner: usize,
    name: []const u8,
    provider: []const u8,
    source_name: []const u8,
    parameters: []const Ir.Type,
    return_type: Ir.Type,
    direct_sites: usize,
    supported_by_prototype: bool,
};

const GlobalInventoryEntry = struct {
    index: usize,
    name: []const u8,
    type: Ir.Type,
    type_name: []const u8,
    mutable: bool,
    runtime_initialized: bool,
    bits: u64,
    extra_bits: []const u64,
    loads: usize,
    stores: usize,
};

const InstructionTag = std.meta.Tag(Ir.Instruction);
const instruction_tag_count = @typeInfo(InstructionTag).@"enum".fields.len;

const InstructionUse = struct {
    sites: [instruction_tag_count]usize = [_]usize{0} ** instruction_tag_count,
    functions: [instruction_tag_count]usize = [_]usize{0} ** instruction_tag_count,
    sites_total: usize = 0,
    conditional_sites: usize = 0,
    abstract_lifetime_sites: usize = 0,
    unsupported_sites: usize = 0,
    unsupported_kinds: usize = 0,
    functions_with_unsupported: usize = 0,
};

const InstructionCoverageEntry = struct {
    name: []const u8,
    support: []const u8,
    sites: usize,
    functions: usize,
};

fn inspectInstructionUse(program: Ir.Program, reachable: []const bool) InstructionUse {
    var result: InstructionUse = .{};
    for (program.functions, 0..) |function, function_index| {
        if (!reachable[function_index]) continue;
        var seen = [_]bool{false} ** instruction_tag_count;
        var function_has_unsupported = false;
        for (function.blocks) |block| for (block.instructions) |instruction| {
            const tag = std.meta.activeTag(instruction);
            const index: usize = @intFromEnum(tag);
            result.sites[index] += 1;
            result.sites_total += 1;
            if (!seen[index]) {
                seen[index] = true;
                result.functions[index] += 1;
            }
            switch (Coverage.classify(tag)) {
                .conditional => result.conditional_sites += 1,
                .abstract_lifetime => result.abstract_lifetime_sites += 1,
                .unsupported => {
                    result.unsupported_sites += 1;
                    function_has_unsupported = true;
                },
            }
        };
        if (function_has_unsupported) result.functions_with_unsupported += 1;
    }
    inline for (@typeInfo(InstructionTag).@"enum".fields) |field| {
        const tag: InstructionTag = @enumFromInt(field.value);
        if (result.sites[field.value] != 0 and Coverage.classify(tag) == .unsupported)
            result.unsupported_kinds += 1;
    }
    return result;
}

fn instructionCoverageEntries(allocator: Allocator, use: InstructionUse) Allocator.Error![]InstructionCoverageEntry {
    var used_kinds: usize = 0;
    inline for (@typeInfo(InstructionTag).@"enum".fields) |field| {
        if (use.sites[field.value] != 0) used_kinds += 1;
    }
    const entries = try allocator.alloc(InstructionCoverageEntry, used_kinds);
    var entry_index: usize = 0;
    inline for (@typeInfo(InstructionTag).@"enum".fields) |field| {
        if (use.sites[field.value] != 0) {
            const tag: InstructionTag = @enumFromInt(field.value);
            entries[entry_index] = .{
                .name = field.name,
                .support = @tagName(Coverage.classify(tag)),
                .sites = use.sites[field.value],
                .functions = use.functions[field.value],
            };
            entry_index += 1;
        }
    }
    return entries;
}

fn reportTypeName(allocator: Allocator, program: Ir.Program, type_value: Ir.Type) Error![]const u8 {
    if (type_value.optionalChild()) |child| {
        return std.fmt.allocPrint(allocator, "{s}?", .{try reportTypeName(allocator, program, child)});
    }
    if (type_value.structureIndex()) |index| {
        if (index >= program.structures.len) return error.InvalidProgram;
        return std.fmt.allocPrint(allocator, "@{s}", .{program.structures[index].name});
    }
    if (type_value.functionIndex()) |index| {
        if (index >= program.function_types.len) return error.InvalidProgram;
        return std.fmt.allocPrint(allocator, "func#{d}", .{index});
    }
    return switch (type_value) {
        .void,
        .bool,
        .int8,
        .uint8,
        .int16,
        .uint16,
        .int32,
        .uint32,
        .int,
        .uint,
        .float32,
        .float64,
        .str,
        .address,
        => @tagName(type_value),
        else => std.fmt.allocPrint(allocator, "type#{d}", .{@intFromEnum(type_value)}),
    };
}

const BoundaryUse = struct {
    direct_sites_by_function: []usize,
    direct_sites: usize = 0,
    indirect_sites: usize = 0,
    unsupported: usize = 0,
    first_unsupported: ?usize = null,
};

fn inspectBoundaryUse(
    allocator: Allocator,
    program: Ir.Program,
    boundaries: []const Silex.Boundary.Function,
    reachable: []const bool,
) Error!BoundaryUse {
    if (reachable.len != program.functions.len) return error.InvalidProgram;
    var result: BoundaryUse = .{ .direct_sites_by_function = try allocator.alloc(usize, boundaries.len) };
    @memset(result.direct_sites_by_function, 0);
    errdefer allocator.free(result.direct_sites_by_function);
    for (program.functions, 0..) |function, function_index| {
        if (!reachable[function_index]) continue;
        for (function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
            .boundary_call => |call| {
                if (call.function >= boundaries.len) return error.InvalidProgram;
                result.direct_sites += 1;
                result.direct_sites_by_function[call.function] += 1;
            },
            .boundary_indirect_call => result.indirect_sites += 1,
            else => {},
        };
    }
    for (result.direct_sites_by_function, 0..) |sites, index| {
        if (sites == 0 or supportsDirectBoundary(boundaries[index])) continue;
        result.unsupported += 1;
        if (result.first_unsupported == null) result.first_unsupported = index;
    }
    return result;
}

const GlobalUse = struct {
    loads: []usize,
    stores: []usize,
    used: usize = 0,
    load_sites: usize = 0,
    store_sites: usize = 0,
};

fn inspectGlobalUse(
    allocator: Allocator,
    program: Ir.Program,
    reachable: []const bool,
) Error!GlobalUse {
    if (reachable.len != program.functions.len) return error.InvalidProgram;
    const loads = try allocator.alloc(usize, program.globals.len);
    errdefer allocator.free(loads);
    const stores = try allocator.alloc(usize, program.globals.len);
    errdefer allocator.free(stores);
    var result: GlobalUse = .{
        .loads = loads,
        .stores = stores,
    };
    @memset(result.loads, 0);
    @memset(result.stores, 0);
    for (program.functions, 0..) |function, function_index| {
        if (!reachable[function_index]) continue;
        for (function.blocks) |block| for (block.instructions) |instruction| switch (instruction) {
            .global_load => |load| {
                if (load.global >= program.globals.len) return error.InvalidProgram;
                result.loads[load.global] += 1;
                result.load_sites += 1;
            },
            .global_store => |store| {
                if (store.global >= program.globals.len) return error.InvalidProgram;
                result.stores[store.global] += 1;
                result.store_sites += 1;
            },
            else => {},
        };
    }
    for (result.loads, result.stores) |load_count, store_count| if (load_count != 0 or store_count != 0) {
        result.used += 1;
    };
    return result;
}

fn supportsStaticGlobal(program: Ir.Program, global: Ir.Global) bool {
    if (global.runtime_initialized or global.extra_bits.len != 0) return false;
    if (global.type.isInteger()) return true;
    const child = global.type.optionalChild() orelse return false;
    return global.bits == 0 and optionalPayloadType(program, child, 0);
}

fn emitGlobalDeclarations(
    output: *std.ArrayList(u8),
    allocator: Allocator,
    program: Ir.Program,
    use: GlobalUse,
) Error!void {
    var emitted = false;
    for (program.globals, 0..) |global, index| {
        if (use.loads[index] == 0 and use.stores[index] == 0) continue;
        if (!supportsStaticGlobal(program, global)) return error.UnsupportedType;
        const initializer = if (global.type.isInteger())
            try std.fmt.allocPrint(allocator, "{d}", .{normalize(global.bits, global.type)})
        else
            "zeroinitializer";
        try appendFmt(output, allocator, "@sx.global.{d} = internal {s} {s} {s}\n", .{
            index,
            if (global.mutable) "global" else "constant",
            try llvmType(allocator, program, global.type),
            initializer,
        });
        emitted = true;
    }
    if (emitted) try output.append(allocator, '\n');
}

const FunctionEmitter = struct {
    allocator: Allocator,
    output: *std.ArrayList(u8),
    program: Ir.Program,
    boundaries: []const Silex.Boundary.Function,
    function: Ir.Function,
    function_id: usize,
    temporary: usize = 0,

    fn emit(self: *FunctionEmitter) Error!void {
        try self.write("; Silex function: {s}\n", .{self.function.name});
        try self.write("define internal fastcc {s} @sx_{d}(ptr %sx.environment", .{ try llvmType(self.allocator, self.program, self.function.return_type), self.function_id });
        for (self.function.parameter_types, 0..) |type_value, index| {
            try self.write(", {s} %v{d}", .{
                try llvmType(self.allocator, self.program, type_value),
                self.function.capture_types.len + index,
            });
        }
        try self.output.appendSlice(self.allocator, ") {\n");
        for (self.function.blocks, 0..) |block, block_id| {
            try self.write("b{d}:\n", .{block_id});
            if (block_id == 0) {
                if (self.function.capture_types.len != 0) {
                    const environment_type = try closureEnvironmentType(
                        self.allocator,
                        self.program,
                        self.function.capture_types,
                    );
                    for (self.function.capture_types, 0..) |type_value, capture| {
                        try self.write("  %capture{d}.address = getelementptr {s}, ptr %sx.environment, i32 0, i32 {d}\n", .{
                            capture,
                            environment_type,
                            capture,
                        });
                        try self.write("  %v{d} = load {s}, ptr %capture{d}.address\n", .{
                            capture,
                            try llvmType(self.allocator, self.program, type_value),
                            capture,
                        });
                    }
                }
                for (self.function.local_types, 0..) |type_value, local| {
                    try self.write("  %local{d} = alloca {s}\n", .{ local, try llvmType(self.allocator, self.program, type_value) });
                }
            }
            for (block.instructions, 0..) |instruction, instruction_index| {
                self.emitInstruction(block_id, instruction_index, instruction) catch |err| {
                    std.debug.print(
                        "silex LLVM evaluation: emitter rejected function '{s}', block {d}, instruction {d} ({s}): {t}\n",
                        .{ self.function.name, block_id, instruction_index, @tagName(instruction), err },
                    );
                    return err;
                };
            }
            self.emitTerminator(block.terminator) catch |err| {
                std.debug.print(
                    "silex LLVM evaluation: emitter rejected function '{s}', block {d}, terminator ({s}): {t}\n",
                    .{ self.function.name, block_id, @tagName(block.terminator), err },
                );
                return err;
            };
        }
        try self.output.appendSlice(self.allocator,
            \\trap:
            \\  call void @exit(i32 1)
            \\  unreachable
            \\}
            \\
        );
    }

    fn emitInstruction(
        self: *FunctionEmitter,
        block_id: usize,
        instruction_index: usize,
        instruction: Ir.Instruction,
    ) Error!void {
        if (Coverage.classify(std.meta.activeTag(instruction)) == .unsupported)
            return error.UnsupportedInstruction;
        switch (instruction) {
            .constant_int => |value| {
                const type_value = try self.valueType(value.result);
                if (type_value.functionIndex() != null) {
                    if (value.bits != 0) return error.UnsupportedInstruction;
                    try self.write("  %v{d} = freeze {s} zeroinitializer\n", .{
                        value.result,
                        try llvmType(self.allocator, self.program, type_value),
                    });
                    return;
                }
                if (!type_value.isInteger()) return error.UnsupportedInstruction;
                const bits = normalize(value.bits, type_value);
                try self.write("  %v{d} = add {s} 0, {d}\n", .{ value.result, try llvmType(self.allocator, self.program, type_value), bits });
            },
            .constant_bool => |value| try self.write(
                "  %v{d} = xor i1 false, {s}\n",
                .{ value.result, if (value.value) "true" else "false" },
            ),
            .constant_str => |value| try self.emitConstantString(block_id, instruction_index, value),
            .constant_bytes => |value| try self.emitConstantBytes(block_id, instruction_index, value),
            .constant_float32 => |value| try self.write(
                "  %v{d} = bitcast i32 {d} to float\n",
                .{ value.result, value.bits },
            ),
            .constant_float64 => |value| try self.write(
                "  %v{d} = bitcast i64 {d} to double\n",
                .{ value.result, value.bits },
            ),
            .optional_null => |value| try self.emitOptionalNull(value),
            .optional_some => |value| try self.emitOptionalSome(value),
            .optional_unwrap => |value| try self.emitOptionalUnwrap(value),
            .copy => |value| try self.copyValue(value.result, value.operand),
            .deep_copy => |value| try self.emitDeepCopy(value.result, value.operand),
            .class_retain => |value| try self.emitClassRetain(value),
            .class_drop => |value| try self.emitClassDrop(value),
            .string_retain => |value| try self.emitStringResource(value, "sx_string_retain"),
            .string_drop => |value| try self.emitStringResource(value, "sx_string_drop"),
            .storage_init => |value| try self.emitStorageInit(value),
            .structure_init => |value| try self.emitStructureInit(value),
            .protocol_init => |value| try self.emitProtocolInit(value),
            .protocol_test => |value| try self.emitProtocolTest(value),
            .protocol_extract => |value| try self.emitProtocolExtract(value),
            .enum_init => |value| try self.emitEnumInit(value),
            .enum_test => |value| try self.emitEnumTest(value),
            .enum_payload => |value| try self.emitEnumPayload(value),
            .enum_raw => |value| try self.emitEnumRaw(value),
            .list_init => |value| try self.emitListInit(value),
            .list_retain => |value| try self.emitListResource(value, "sx_retain"),
            .list_drop => |value| try self.emitListResource(value, "sx_drop"),
            .list_edit => |value| try self.emitListEdit(block_id, value),
            .field_load => |value| try self.emitFieldLoad(value),
            .field_store => |value| try self.emitFieldStore(value),
            .collection_load => |value| try self.emitCollectionLoad(block_id, value),
            .collection_reference => |value| try self.emitCollectionReference(block_id, value),
            .collection_replace => |value| try self.emitCollectionReplace(block_id, value),
            .collection_count => |value| try self.emitCollectionCount(value),
            .collection_slice => |value| try self.emitCollectionSlice(value),
            .collection_view => |value| try self.emitCollectionView(block_id, value),
            .function_reference => |value| try self.emitFunctionReference(value),
            .local_load => |value| try self.write(
                "  %v{d} = load {s}, ptr %local{d}\n",
                .{ value.result, try llvmType(self.allocator, self.program, try self.valueType(value.result)), value.local },
            ),
            .local_store => |value| try self.write(
                "  store {s} %v{d}, ptr %local{d}\n",
                .{ try llvmType(self.allocator, self.program, try self.valueType(value.operand)), value.operand, value.local },
            ),
            .global_load => |value| try self.emitGlobalLoad(value),
            .global_store => |value| try self.emitGlobalStore(value),
            .local_address => |value| try self.emitLocalAddress(value),
            .reference_load => |value| try self.emitReferenceLoad(value),
            .address_load => |value| try self.emitAddressLoad(value),
            .address_store => |value| try self.emitAddressStore(value),
            .reference_store => |value| try self.emitReferenceStore(value),
            .reference_field => |value| try self.emitReferenceField(value),
            .reference_optional => |value| try self.emitReferenceOptional(value),
            .string_address => |value| try self.emitStringAddress(value),
            .string_byte_count => |value| try self.emitStringByteCount(value),
            .string_byte_at => |value| try self.emitStringByteAt(block_id, value),
            .string_from_bytes => |value| try self.emitStringFromBytes(block_id, value),
            .string_count => |value| try self.emitStringCount(value),
            .string_concat => |value| try self.emitStringConcat(block_id, value),
            .format_value => |value| try self.emitFormatValue(value),
            .unary => |value| try self.emitNegate(block_id, value),
            .binary => |value| try self.emitBinary(block_id, value),
            .convert => |value| try self.emitConvert(block_id, value),
            .call => |value| try self.emitCall(value),
            .indirect_call => |value| try self.emitIndirectCall(value),
            .boundary_call => |value| try self.emitBoundaryCall(value),
            .print => |value| try self.emitPrint(value),
            .assert => |value| try self.emitAssert(block_id, value),
            .mutex_lock => try self.emitMutexLock(),
            .mutex_unlock => try self.emitMutexUnlock(),
            else => return error.UnsupportedInstruction,
        }
    }

    fn emitMutexLock(self: *FunctionEmitter) Error!void {
        try self.output.appendSlice(
            self.allocator,
            "  call void @os_unfair_recursive_lock_lock_with_options(ptr @sx.mutex, i64 0)\n",
        );
    }

    fn emitMutexUnlock(self: *FunctionEmitter) Error!void {
        try self.output.appendSlice(
            self.allocator,
            "  call void @os_unfair_recursive_lock_unlock(ptr @sx.mutex)\n",
        );
    }

    fn emitStorageInit(self: *FunctionEmitter, value: Ir.Instruction.StorageInit) Error!void {
        try self.write("  %v{d} = freeze {s} zeroinitializer\n", .{
            value.result,
            try llvmType(self.allocator, self.program, try self.valueType(value.result)),
        });
    }

    fn emitConstantString(
        self: *FunctionEmitter,
        block_id: usize,
        instruction_index: usize,
        value: Ir.Instruction.ConstantStr,
    ) Error!void {
        if (try self.valueType(value.result) != .str) return error.InvalidProgram;
        try self.write(
            "  %v{d} = getelementptr {{ i64, [{d} x i8] }}, ptr @sx.string.{d}.{d}.{d}, i32 0, i32 0\n",
            .{ value.result, value.value.len, self.function_id, block_id, instruction_index },
        );
    }

    fn emitConstantBytes(
        self: *FunctionEmitter,
        block_id: usize,
        instruction_index: usize,
        value: Ir.Instruction.ConstantBytes,
    ) Error!void {
        const type_value = try self.valueType(value.result);
        const collection = try self.collectionInfo(type_value);
        if (collection.element != .uint8 or collection.length != null or collection.view)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        const type_name = try llvmType(self.allocator, self.program, type_value);
        // The semantic IR immediately installs the literal's owning root with
        // list_retain. Start at zero so that this explicit retain owns it.
        try self.write("  %t{d}.bytes.storage = call fastcc ptr @sx_unowned_alloc(i64 {d})\n", .{
            serial,
            value.value.len,
        });
        if (value.value.len != 0) try self.write(
            "  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.bytes.storage, ptr @sx.bytes.{d}.{d}.{d}, i64 {d}, i1 false)\n",
            .{ serial, self.function_id, block_id, instruction_index, value.value.len },
        );
        try self.write("  %t{d}.bytes.value = insertvalue {s} poison, ptr %t{d}.bytes.storage, 0\n", .{
            serial,
            type_name,
            serial,
        });
        try self.write("  %v{d} = insertvalue {s} %t{d}.bytes.value, i64 {d}, 1\n", .{
            value.result,
            type_name,
            serial,
            value.value.len,
        });
    }

    fn emitStringResource(self: *FunctionEmitter, value: Ir.Instruction.ListResource, comptime operation: []const u8) Error!void {
        if (try self.valueType(value.operand) != .str)
            return error.UnsupportedInstruction;
        try self.write("  call fastcc void @{s}(ptr %v{d}, i64 {d})\n", .{
            operation,
            value.operand,
            if (value.ownership == .root) @as(i8, -24) else -16,
        });
    }

    fn emitStringCount(self: *FunctionEmitter, value: Ir.Instruction.StringCount) Error!void {
        if (try self.valueType(value.operand) != .str or try self.valueType(value.result) != .int)
            return error.InvalidProgram;
        try self.write("  %v{d} = call fastcc i64 @sx_string_count(ptr %v{d})\n", .{ value.result, value.operand });
    }

    fn emitStringAddress(self: *FunctionEmitter, value: Ir.Instruction.StringProjection) Error!void {
        if (try self.valueType(value.operand) != .str or try self.valueType(value.result) != .address)
            return error.InvalidProgram;
        try self.write("  %v{d} = getelementptr i8, ptr %v{d}, i64 8\n", .{ value.result, value.operand });
    }

    fn emitStringByteCount(self: *FunctionEmitter, value: Ir.Instruction.StringProjection) Error!void {
        if (try self.valueType(value.operand) != .str or try self.valueType(value.result) != .uint)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        try self.write("  %t{d}.string.tagged = load i64, ptr %v{d}\n", .{ serial, value.operand });
        try self.write("  %v{d} = and i64 %t{d}.string.tagged, 9223372036854775807\n", .{ value.result, serial });
    }

    fn emitStringByteAt(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.StringByteAt) Error!void {
        if (try self.valueType(value.operand) != .str or
            try self.valueType(value.index) != .uint or
            try self.valueType(value.result) != .uint8)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        try self.write("  %t{d}.string.tagged = load i64, ptr %v{d}\n", .{ serial, value.operand });
        try self.write("  %t{d}.string.length = and i64 %t{d}.string.tagged, 9223372036854775807\n", .{ serial, serial });
        try self.write("  %t{d}.string.invalid = icmp uge i64 %v{d}, %t{d}.string.length\n", .{ serial, value.index, serial });
        try self.write("  br i1 %t{d}.string.invalid, label %trap, label %b{d}.string{d}\n", .{ serial, block_id, serial });
        try self.write("b{d}.string{d}:\n", .{ block_id, serial });
        try self.write("  %t{d}.string.offset = add i64 %v{d}, 8\n", .{ serial, value.index });
        try self.write("  %t{d}.string.address = getelementptr i8, ptr %v{d}, i64 %t{d}.string.offset\n", .{ serial, value.operand, serial });
        try self.write("  %v{d} = load i8, ptr %t{d}.string.address\n", .{ value.result, serial });
    }

    fn emitStringFromBytes(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.StringFromBytes) Error!void {
        if (try self.valueType(value.result) != .str) return error.InvalidProgram;
        const bytes_type = try self.valueType(value.bytes);
        const bytes = try self.collectionInfo(bytes_type);
        if (!bytes.view or bytes.element != .uint8) return error.InvalidProgram;

        const serial = self.nextTemporary();
        const bytes_name = try llvmType(self.allocator, self.program, bytes_type);
        try self.write("  %t{d}.from_bytes.data = extractvalue {s} %v{d}, 0\n", .{ serial, bytes_name, value.bytes });
        try self.write("  %t{d}.from_bytes.count = extractvalue {s} %v{d}, 1\n", .{ serial, bytes_name, value.bytes });
        try self.write("  %t{d}.from_bytes.count.invalid = icmp slt i64 %t{d}.from_bytes.count, 0\n", .{ serial, serial });
        try self.write("  %t{d}.from_bytes.allocation.checked = call {{ i64, i1 }} @llvm.uadd.with.overflow.i64(i64 %t{d}.from_bytes.count, i64 8)\n", .{ serial, serial });
        try self.write("  %t{d}.from_bytes.allocation = extractvalue {{ i64, i1 }} %t{d}.from_bytes.allocation.checked, 0\n", .{ serial, serial });
        try self.write("  %t{d}.from_bytes.allocation.overflow = extractvalue {{ i64, i1 }} %t{d}.from_bytes.allocation.checked, 1\n", .{ serial, serial });
        try self.write("  %t{d}.from_bytes.invalid = or i1 %t{d}.from_bytes.count.invalid, %t{d}.from_bytes.allocation.overflow\n", .{ serial, serial, serial });
        try self.write("  br i1 %t{d}.from_bytes.invalid, label %trap, label %b{d}.from_bytes{d}\n", .{ serial, block_id, serial });
        try self.write("b{d}.from_bytes{d}:\n", .{ block_id, serial });
        try self.write("  %t{d}.from_bytes.descriptor = call fastcc ptr @sx_alloc(i64 %t{d}.from_bytes.allocation)\n", .{ serial, serial });
        try self.write("  %t{d}.from_bytes.tagged = or i64 %t{d}.from_bytes.count, -9223372036854775808\n", .{ serial, serial });
        try self.write("  store i64 %t{d}.from_bytes.tagged, ptr %t{d}.from_bytes.descriptor\n", .{ serial, serial });
        try self.write("  %t{d}.from_bytes.destination = getelementptr i8, ptr %t{d}.from_bytes.descriptor, i64 8\n", .{ serial, serial });
        try self.write(
            "  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.from_bytes.destination, ptr %t{d}.from_bytes.data, i64 %t{d}.from_bytes.count, i1 false)\n",
            .{ serial, serial, serial },
        );
        try self.write("  %v{d} = getelementptr i8, ptr %t{d}.from_bytes.descriptor, i64 0\n", .{ value.result, serial });
    }

    fn emitStringConcat(self: *FunctionEmitter, block_id: usize, value: Ir.Instruction.StringConcat) Error!void {
        if (try self.valueType(value.left) != .str or
            try self.valueType(value.right) != .str or
            try self.valueType(value.result) != .str)
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        try self.write("  %t{d}.left.tagged = load i64, ptr %v{d}\n", .{ serial, value.left });
        try self.write("  %t{d}.left.length = and i64 %t{d}.left.tagged, 9223372036854775807\n", .{ serial, serial });
        try self.write("  %t{d}.right.tagged = load i64, ptr %v{d}\n", .{ serial, value.right });
        try self.write("  %t{d}.right.length = and i64 %t{d}.right.tagged, 9223372036854775807\n", .{ serial, serial });
        try self.write("  %t{d}.length.checked = call {{ i64, i1 }} @llvm.uadd.with.overflow.i64(i64 %t{d}.left.length, i64 %t{d}.right.length)\n", .{ serial, serial, serial });
        try self.write("  %t{d}.length = extractvalue {{ i64, i1 }} %t{d}.length.checked, 0\n", .{ serial, serial });
        try self.write("  %t{d}.length.overflow = extractvalue {{ i64, i1 }} %t{d}.length.checked, 1\n", .{ serial, serial });
        try self.write("  %t{d}.allocation.checked = call {{ i64, i1 }} @llvm.uadd.with.overflow.i64(i64 %t{d}.length, i64 8)\n", .{ serial, serial });
        try self.write("  %t{d}.allocation = extractvalue {{ i64, i1 }} %t{d}.allocation.checked, 0\n", .{ serial, serial });
        try self.write("  %t{d}.allocation.overflow = extractvalue {{ i64, i1 }} %t{d}.allocation.checked, 1\n", .{ serial, serial });
        try self.write("  %t{d}.overflow = or i1 %t{d}.length.overflow, %t{d}.allocation.overflow\n", .{ serial, serial, serial });
        try self.write("  br i1 %t{d}.overflow, label %trap, label %b{d}.concat{d}\n", .{ serial, block_id, serial });
        try self.write("b{d}.concat{d}:\n", .{ block_id, serial });
        try self.write("  %t{d}.descriptor = call fastcc ptr @sx_alloc(i64 %t{d}.allocation)\n", .{ serial, serial });
        try self.write("  %t{d}.tagged = or i64 %t{d}.length, -9223372036854775808\n", .{ serial, serial });
        try self.write("  store i64 %t{d}.tagged, ptr %t{d}.descriptor\n", .{ serial, serial });
        try self.write("  %t{d}.data = getelementptr i8, ptr %t{d}.descriptor, i64 8\n", .{ serial, serial });
        try self.write("  %t{d}.left.data = getelementptr i8, ptr %v{d}, i64 8\n", .{ serial, value.left });
        try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.data, ptr %t{d}.left.data, i64 %t{d}.left.length, i1 false)\n", .{ serial, serial, serial });
        try self.write("  %t{d}.right.destination = getelementptr i8, ptr %t{d}.data, i64 %t{d}.left.length\n", .{ serial, serial, serial });
        try self.write("  %t{d}.right.data = getelementptr i8, ptr %v{d}, i64 8\n", .{ serial, value.right });
        try self.write("  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.right.destination, ptr %t{d}.right.data, i64 %t{d}.right.length, i1 false)\n", .{ serial, serial, serial });
        try self.write("  %v{d} = getelementptr i8, ptr %t{d}.descriptor, i64 0\n", .{ value.result, serial });
    }

    fn emitFormatValue(self: *FunctionEmitter, value: Ir.Instruction.FormatValue) Error!void {
        const operand_type = try self.valueType(value.operand);
        if (try self.valueType(value.result) != .str) return error.InvalidProgram;
        if (operand_type == .bool) {
            try self.write(
                "  %v{d} = select i1 %v{d}, ptr @sx.format.true, ptr @sx.format.false\n",
                .{ value.result, value.operand },
            );
            return;
        }
        if (operand_type == .str) {
            try self.write("  %v{d} = getelementptr i8, ptr %v{d}, i64 0\n", .{ value.result, value.operand });
            return;
        }
        if (!operand_type.isNumeric()) return error.UnsupportedInstruction;

        const serial = self.nextTemporary();
        try self.write("  %t{d}.format.scratch = alloca [384 x i8]\n", .{serial});
        try self.write(
            "  %t{d}.format.output = getelementptr [384 x i8], ptr %t{d}.format.scratch, i32 0, i32 0\n",
            .{ serial, serial },
        );
        if (operand_type.isInteger()) {
            if (operand_type.bitWidth() == 64) {
                try self.write("  %t{d}.format.bits = add i64 0, %v{d}\n", .{ serial, value.operand });
            } else {
                try self.write(
                    "  %t{d}.format.bits = {s} i{d} %v{d} to i64\n",
                    .{ serial, if (operand_type.isSignedInteger()) "sext" else "zext", operand_type.bitWidth(), value.operand },
                );
            }
            try self.write(
                "  %t{d}.format.length = call i64 @{s}(i64 %t{d}.format.bits, ptr %t{d}.format.output)\n",
                .{ serial, if (operand_type.isSignedInteger()) "silex_format_signed" else "silex_format_unsigned", serial, serial },
            );
        } else if (operand_type == .float32) {
            try self.write("  %t{d}.format.f32 = bitcast float %v{d} to i32\n", .{ serial, value.operand });
            try self.write("  %t{d}.format.bits = zext i32 %t{d}.format.f32 to i64\n", .{ serial, serial });
            try self.write(
                "  %t{d}.format.length = call i64 @silex_format_float(i64 %t{d}.format.bits, ptr %t{d}.format.output, i64 0)\n",
                .{ serial, serial, serial },
            );
        } else {
            try self.write("  %t{d}.format.bits = bitcast double %v{d} to i64\n", .{ serial, value.operand });
            try self.write(
                "  %t{d}.format.length = call i64 @silex_format_float(i64 %t{d}.format.bits, ptr %t{d}.format.output, i64 1)\n",
                .{ serial, serial, serial },
            );
        }
        try self.write("  %t{d}.format.allocation = add i64 %t{d}.format.length, 8\n", .{ serial, serial });
        try self.write("  %t{d}.format.descriptor = call fastcc ptr @sx_alloc(i64 %t{d}.format.allocation)\n", .{ serial, serial });
        try self.write("  %t{d}.format.tagged = or i64 %t{d}.format.length, -9223372036854775808\n", .{ serial, serial });
        try self.write("  store i64 %t{d}.format.tagged, ptr %t{d}.format.descriptor\n", .{ serial, serial });
        try self.write("  %t{d}.format.data = getelementptr i8, ptr %t{d}.format.descriptor, i64 8\n", .{ serial, serial });
        try self.write(
            "  call void @llvm.memcpy.p0.p0.i64(ptr %t{d}.format.data, ptr %t{d}.format.output, i64 %t{d}.format.length, i1 false)\n",
            .{ serial, serial, serial },
        );
        try self.write("  %v{d} = getelementptr i8, ptr %t{d}.format.descriptor, i64 0\n", .{ value.result, serial });
    }

    fn emitGlobalLoad(self: *FunctionEmitter, value: Ir.Instruction.GlobalLoad) Error!void {
        if (value.global >= self.program.globals.len) return error.InvalidProgram;
        const global = self.program.globals[value.global];
        if (!supportsStaticGlobal(self.program, global) or try self.valueType(value.result) != global.type)
            return error.InvalidProgram;
        try self.write("  %v{d} = load {s}, ptr @sx.global.{d}\n", .{
            value.result,
            try llvmType(self.allocator, self.program, global.type),
            value.global,
        });
    }

    fn emitAddressLoad(self: *FunctionEmitter, value: Ir.Instruction.AddressLoad) Error!void {
        const address_type = try self.valueType(value.address);
        if ((address_type != .address and address_type != .uint) or
            try self.valueType(value.byte_offset) != .uint or
            try self.valueType(value.result) != value.type or
            (!value.type.isNumeric() and value.type != .address))
            return error.InvalidProgram;
        const serial = self.nextTemporary();
        if (address_type == .uint) {
            try self.write("  %t{d}.raw.base = inttoptr i64 %v{d} to ptr\n", .{ serial, value.address });
        } else {
            try self.write("  %t{d}.raw.base = getelementptr i8, ptr %v{d}, i64 0\n", .{ serial, value.address });
        }
        try self.write(
            "  %t{d}.raw.address = getelementptr i8, ptr %t{d}.raw.base, i64 %v{d}\n",
            .{ serial, serial, value.byte_offset },
        );
        try self.write(
            "  %v{d} = load {s}, ptr %t{d}.raw.address, align 1\n",
            .{ value.result, try llvmType(self.allocator, self.program, value.type), serial },
        );
    }

    fn emitAddressStore(self: *FunctionEmitter, value: Ir.Instruction.AddressStore) Error!void {
